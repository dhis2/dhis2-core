package org.hisp.dhis.visualization;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import org.hibernate.cache.spi.access.AccessType;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.tuple.entity.EntityMetamodel;
import org.hisp.dhis.common.IdentifiableObjectManager;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/**
 * Tests the persistence mapping of {@link Axis} to the axis table and its use as the element of
 * {@link Visualization#getOptionalAxes()} (visualization_axis).
 */
@Transactional
class AxisStoreTest extends PostgresIntegrationTestBase {

  @Autowired private VisualizationService visualizationService;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("dimensionalItem and axis are written to their columns and read back from them")
  void testColumnsRoundTrip() {
    Axis axis = axis("deUidColumn", 2);
    long visualizationId = saveVisualization('A', axis);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select dimensionalitem, axis from axis where axisid = ?", axis.getId());
    assertEquals("deUidColumn", row.get("dimensionalitem"));
    assertEquals(2, row.get("axis"));

    clearSessionAndSecondLevelCache();

    Axis reloaded = visualizationService.getVisualization(visualizationId).getOptionalAxes().get(0);
    assertEquals(axis.getId(), reloaded.getId());
    assertEquals("deUidColumn", reloaded.getDimensionalItem());
    assertEquals(2, reloaded.getAxis());
  }

  @Test
  @DisplayName("dimensionalItem and axis are mapped not-null")
  void testNullability() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] nullable = persister.getPropertyNullability();

    assertFalse(nullable[metamodel.getPropertyIndex("dimensionalItem")]);
    assertFalse(nullable[metamodel.getPropertyIndex("axis")]);
  }

  @Test
  @DisplayName("the entity is second-level cached with the read-write strategy")
  void testReadWriteEntityCache() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName(
      "a visualization saves its optional axes by cascade and keeps their order in"
          + " visualization_axis")
  void testVisualizationOwnsOrderedAxes() {
    Axis first = axis("deUidFirst", 1);
    Axis second = axis("deUidSecond", 0);
    Axis third = axis("deUidThird", 1);
    long visualizationId = saveVisualization('B', first, second, third);

    assertEquals(List.of(first.getId(), second.getId(), third.getId()), joinRows(visualizationId));

    clearSessionAndSecondLevelCache();

    List<Axis> reloaded = visualizationService.getVisualization(visualizationId).getOptionalAxes();
    assertEquals(
        List.of("deUidFirst", "deUidSecond", "deUidThird"),
        reloaded.stream().map(Axis::getDimensionalItem).toList());
    assertEquals(List.of(1, 0, 1), reloaded.stream().map(Axis::getAxis).toList());
  }

  @Test
  @DisplayName("removing an axis from a visualization deletes its join row and its axis row")
  void testRemoveAxisDeletesOrphan() {
    Axis kept = axis("deUidKept", 0);
    Axis removed = axis("deUidRemoved", 1);
    long visualizationId = saveVisualization('D', kept, removed);

    clearSessionAndSecondLevelCache();

    Visualization loaded = visualizationService.getVisualization(visualizationId);
    loaded.getOptionalAxes().removeIf(a -> "deUidRemoved".equals(a.getDimensionalItem()));
    manager.update(loaded);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    assertEquals(List.of(kept.getId()), joinRows(visualizationId));
    assertEquals(1, countAxisRows(kept.getId()));
    assertEquals(0, countAxisRows(removed.getId()));
  }

  /** Reloads must hit the database, not the read-write second-level cache of Axis/optionalAxes. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Axis.class);
  }

  private static Axis axis(String dimensionalItem, int axisNumber) {
    Axis axis = new Axis();
    axis.setDimensionalItem(dimensionalItem);
    axis.setAxis(axisNumber);
    return axis;
  }

  private long saveVisualization(char uniqueCharacter, Axis... axes) {
    Visualization visualization = createVisualization(uniqueCharacter);
    visualization.setOptionalAxes(new ArrayList<>(List.of(axes)));
    long id = visualizationService.save(visualization);
    entityManager.flush();
    return id;
  }

  /** Axis ids of the visualization's join rows, ordered by sort_order. */
  private List<Long> joinRows(long visualizationId) {
    return jdbcTemplate.queryForList(
        "select axisid from visualization_axis where visualizationid = ? order by sort_order",
        Long.class,
        visualizationId);
  }

  private int countAxisRows(long axisId) {
    return jdbcTemplate.queryForObject(
        "select count(*) from axis where axisid = ?", Integer.class, axisId);
  }
}
