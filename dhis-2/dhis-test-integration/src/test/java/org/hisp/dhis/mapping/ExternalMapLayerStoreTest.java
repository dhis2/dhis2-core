@Transactional
class ExternalMapLayerStoreTest extends PostgresIntegrationTestBase {
  @Autowired private ExternalMapLayerStore store;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every ExternalMapLayer-specific property is written to its column")
  void shouldWriteEveryExternalMapLayerSpecificColumn() {
    ExternalMapLayer layer = saveFullLayer();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, url, attribution, layers, legendsetid, legendseturl, description,"
                + " descriptionurl, image, translations::text as translations,"
                + " sharing->>'public' as publicaccess"
                + " from externalmaplayer where externalmaplayerid = ?",
            layer.getId());
    assertEquals("EML_A", row.get("code"));
    assertEquals("Layer A", row.get("name"));
    assertEquals("https://tiles.example.org/{z}/{x}/{y}.png", row.get("url"));
    assertEquals("Example contributors", row.get("attribution"));
    assertEquals("roads,rivers", row.get("layers"));
    assertEquals(layer.getLegendSet().getId(), row.get("legendsetid"));
    assertEquals("https://legend.example.org", row.get("legendseturl"));
    assertEquals("Description A", row.get("description"));
    assertEquals("https://about.example.org", row.get("descriptionurl"));
    assertEquals("data:image/png;base64,iVBORw0KGgo=", row.get("image"));
    assertTrue(((String) row.get("translations")).contains("\"Couche A\""));
    assertEquals("rw------", row.get("publicaccess"));
  }

  @Test
  @DisplayName("the enum columns hold the Java-serialized enum constants")
  void shouldWriteEnumColumnsAsJavaSerializedConstants() {
    ExternalMapLayer layer = saveFullLayer();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select mapservice, imageformat, maplayerposition from externalmaplayer"
                + " where externalmaplayerid = ?",
            layer.getId());
    assertSame(MapService.WMS, deserialize((byte[]) row.get("mapservice")));
    assertSame(ImageFormat.JPG, deserialize((byte[]) row.get("imageformat")));
    assertSame(MapLayerPosition.OVERLAY, deserialize((byte[]) row.get("maplayerposition")));
  }

  @Test
  @DisplayName("Java-serialized enum constants written outside Hibernate are read back")
  void shouldReadJavaSerializedEnumColumns() {
    ExternalMapLayer layer = save(createLayer('B'));
    jdbcTemplate.update(
        "update externalmaplayer set mapservice = ?, imageformat = ?, maplayerposition = ?"
            + " where externalmaplayerid = ?",
        serialize(MapService.TMS),
        serialize(ImageFormat.PNG),
        serialize(MapLayerPosition.BASEMAP),
        layer.getId());

    ExternalMapLayer reloaded = reload(layer);

    assertEquals(MapService.TMS, reloaded.getMapService());
    assertEquals(ImageFormat.PNG, reloaded.getImageFormat());
    assertEquals(MapLayerPosition.BASEMAP, reloaded.getMapLayerPosition());
  }

  @Test
  @DisplayName("every ExternalMapLayer-specific property is read back from its column")
  void shouldReadBackEveryExternalMapLayerSpecificProperty() {
    ExternalMapLayer layer = saveFullLayer();

    ExternalMapLayer reloaded = reload(layer);

    assertEquals("EML_A", reloaded.getCode());
    assertEquals("Layer A", reloaded.getName());
    assertEquals(MapService.WMS, reloaded.getMapService());
    assertEquals("https://tiles.example.org/{z}/{x}/{y}.png", reloaded.getUrl());
    assertEquals("Example contributors", reloaded.getAttribution());
    assertEquals("roads,rivers", reloaded.getLayers());
    assertEquals(ImageFormat.JPG, reloaded.getImageFormat());
    assertEquals(MapLayerPosition.OVERLAY, reloaded.getMapLayerPosition());
    assertEquals(layer.getLegendSet().getUid(), reloaded.getLegendSet().getUid());
    assertEquals("https://legend.example.org", reloaded.getLegendSetUrl());
    assertEquals("Description A", reloaded.getDescription());
    assertEquals("https://about.example.org", reloaded.getDescriptionUrl());
    assertEquals("data:image/png;base64,iVBORw0KGgo=", reloaded.getImage());
    assertEquals(
        Set.of(
            new Translation(new Locale("fr"), "NAME", "Couche A"),
            new Translation(new Locale("fr"), "ATTRIBUTION", "Contributeurs")),
        reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(getAdminUser().getUid(), reloaded.getSharing().getOwner());
  }

  @Test
  @DisplayName("the enum properties are bound as serializable types of their enum class")
  void shouldBindEnumPropertiesAsSerializableTypes() {
    assertSerializableType("mapService", MapService.class);
    assertSerializableType("imageFormat", ImageFormat.class);
    assertSerializableType("mapLayerPosition", MapLayerPosition.class);
  }

  @Test
  @DisplayName("url, attribution, layers and legendSetUrl are text, the others varchar")
  void shouldBindTextAndVarcharColumns() {
    EntityPersister persister = persister();
    for (String property : new String[] {"url", "attribution", "layers", "legendSetUrl"}) {
      assertInstanceOf(TextType.class, persister.getPropertyType(property), property);
    }
    for (String property :
        new String[] {"code", "name", "description", "descriptionUrl", "image"}) {
      assertInstanceOf(StringType.class, persister.getPropertyType(property), property);
    }
    CustomType sharing = assertInstanceOf(CustomType.class, persister.getPropertyType("sharing"));
    assertInstanceOf(SharingJsonBinaryType.class, sharing.getUserType());
  }

  @Test
  @DisplayName("the legend set is a lazy many-to-one reference")
  void shouldMapLegendSetAsLazyReference() {
    ManyToOneType type =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("legendSet"));

    assertFalse(type.isEager(null));
    assertEquals(LegendSet.class.getName(), type.getAssociatedEntityName());
  }

  @Test
  @DisplayName(
      "name, url and the enums are not-null; the other ExternalMapLayer-specific properties are nullable")
  void shouldMapNameUrlAndEnumsNotNullAndTheOthersNullable() {
    for (String property :
        new String[] {"name", "url", "mapService", "imageFormat", "mapLayerPosition"}) {
      assertFalse(isNullable(property), property + " is mapped nullable");
    }
    for (String property :
        new String[] {
          "code",
          "attribution",
          "layers",
          "legendSet",
          "legendSetUrl",
          "description",
          "descriptionUrl",
          "image",
          "createdBy",
          "translations",
          "sharing"
        }) {
      assertTrue(isNullable(property), property + " is mapped not-null");
    }
  }

  @Test
  @DisplayName("the entity is not second-level cached")
  void shouldNotCacheEntity() {
    assertFalse(persister().canReadFromCache());
  }

  @Test
  @DisplayName("an uninitialized proxy equals an instance with the same uid, code and name")
  void shouldEqualProxyWithSameIdentity() {
    ExternalMapLayer saved = save(createLayer('C'));
    clearSession();
    ExternalMapLayer copy = new ExternalMapLayer(saved.getName());
    copy.setUid(saved.getUid());
    copy.setCode(saved.getCode());

    ExternalMapLayer proxy = entityManager.getReference(ExternalMapLayer.class, saved.getId());

    assertInstanceOf(HibernateProxy.class, proxy);
    assertEquals(copy, proxy);
    assertEquals(proxy, copy);
    assertEquals(copy.hashCode(), proxy.hashCode());
  }

  @Test
  @DisplayName("null translations and sharing columns are read as empty")
  void shouldReadNullJsonbColumnsAsEmpty() {
    ExternalMapLayer saved = save(createLayer('D'));
    jdbcTemplate.update(
        "update externalmaplayer set translations = null, sharing = null"
            + " where externalmaplayerid = ?",
        saved.getId());

    ExternalMapLayer reloaded = reload(saved);

    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals(reloaded.getName(), reloaded.getDisplayName());
    assertEquals(reloaded.getAttribution(), reloaded.getDisplayAttribution());
    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
  }

  private ExternalMapLayer saveFullLayer() {
    LegendSet legendSet = createLegendSet('A');
    manager.save(legendSet);

    ExternalMapLayer layer = new ExternalMapLayer("Layer A");
    layer.setAutoFields();
    layer.setCode("EML_A");
    layer.setMapService(MapService.WMS);
    layer.setUrl("https://tiles.example.org/{z}/{x}/{y}.png");
    layer.setAttribution("Example contributors");
    layer.setLayers("roads,rivers");
    layer.setImageFormat(ImageFormat.JPG);
    layer.setMapLayerPosition(MapLayerPosition.OVERLAY);
    layer.setLegendSet(legendSet);
    layer.setLegendSetUrl("https://legend.example.org");
    layer.setDescription("Description A");
    layer.setDescriptionUrl("https://about.example.org");
    layer.setImage("data:image/png;base64,iVBORw0KGgo=");
    layer.setTranslations(
        Set.of(
            new Translation(new Locale("fr"), "NAME", "Couche A"),
            new Translation(new Locale("fr"), "ATTRIBUTION", "Contributeurs")));
    layer.getSharing().setPublicAccess("rw------");
    layer.getSharing().setOwner(getAdminUser().getUid());
    store.save(layer, false);
    entityManager.flush();
    return layer;
  }

  private static ExternalMapLayer createLayer(char uniqueCharacter) {
    ExternalMapLayer layer = new ExternalMapLayer("Layer " + uniqueCharacter);
    layer.setCode("EML_" + uniqueCharacter);
    layer.setMapService(MapService.XYZ);
    layer.setUrl("https://tiles.example.org/" + uniqueCharacter);
    layer.setImageFormat(ImageFormat.PNG);
    layer.setMapLayerPosition(MapLayerPosition.BASEMAP);
    return layer;
  }

  private void assertSerializableType(String property, Class<?> enumClass) {
    SerializableType<?> type =
        assertInstanceOf(SerializableType.class, persister().getPropertyType(property), property);
    assertEquals(enumClass, type.getReturnedClass(), property);
  }

  private static byte[] serialize(Serializable value) {
    ByteArrayOutputStream bytes = new ByteArrayOutputStream();
    try (ObjectOutputStream out = new ObjectOutputStream(bytes)) {
      out.writeObject(value);
    } catch (IOException e) {
      throw new IllegalStateException(e);
    }
    return bytes.toByteArray();
  }

  private static Object deserialize(byte[] bytes) {
    try (ObjectInputStream in = new ObjectInputStream(new ByteArrayInputStream(bytes))) {
      return in.readObject();
    } catch (IOException | ClassNotFoundException e) {
      throw new IllegalStateException(e);
    }
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ExternalMapLayer.class);
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private ExternalMapLayer save(ExternalMapLayer layer) {
    store.save(layer);
    entityManager.flush();
    return layer;
  }

  /** Reloads the layer from the database, bypassing the session. */
  private ExternalMapLayer reload(ExternalMapLayer layer) {
    clearSession();
    return store.get(layer.getId());
  }
}
