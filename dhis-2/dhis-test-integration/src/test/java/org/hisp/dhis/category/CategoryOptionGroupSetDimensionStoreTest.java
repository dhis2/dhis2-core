package org.hisp.dhis.category;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.util.ArrayList;
import java.util.List;
import org.hibernate.cache.spi.access.AccessType;
import org.hibernate.cache.spi.support.CollectionNonStrictReadWriteAccess;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.NoopOptimizer;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.collection.CollectionPersister;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.type.ManyToOneType;
import org.hisp.dhis.common.IdentifiableObjectManager;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.hisp.dhis.visualization.Visualization;
import org.hisp.dhis.visualization.VisualizationService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/**
 * Tests the persistence mapping of {@link CategoryOptionGroupSetDimension} to the
 * categoryoptiongroupsetdimension and categoryoptiongroupsetdimension_items tables, and its use as
 * the element of {@link Visualization#getCategoryOptionGroupSetDimensions()}.
 */
@Transactional
class CategoryOptionGroupSetDimensionStoreTest extends PostgresIntegrationTestBase {

  private static final String ITEMS_ROLE =
      CategoryOptionGroupSetDimension.class.getName() + ".items";

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private VisualizationService visualizationService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private CategoryOptionGroup groupA;

  private CategoryOptionGroup groupB;

  private CategoryOptionGroup groupC;

  private CategoryOptionGroupSet groupSet;

  @BeforeEach
  void setUp() {
    groupA = createCategoryOptionGroup('A');
    groupB = createCategoryOptionGroup('B');
    groupC = createCategoryOptionGroup('C');
    manager.save(groupA);
    manager.save(groupB);
    manager.save(groupC);

    groupSet = createCategoryOptionGroupSet('S', groupA, groupB, groupC);
    manager.save(groupSet);
  }

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on hibernate_sequence, one nextval per id")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName("the dimension is written to categoryoptiongroupsetid and read back from it")
  void testDimensionRoundTrip() {
    CategoryOptionGroupSetDimension dimension = persist(dimension(groupA));

    assertEquals(
        groupSet.getId(),
        jdbcTemplate.queryForObject(
            "select categoryoptiongroupsetid from categoryoptiongroupsetdimension"
                + " where categoryoptiongroupsetdimensionid = ?",
            Long.class,
            dimension.getId()));

    clearSessionAndSecondLevelCache();

    CategoryOptionGroupSetDimension reloaded = reload(dimension);
    assertEquals(dimension.getId(), reloaded.getId());
    assertEquals(groupSet.getUid(), reloaded.getDimension().getUid());
  }

  @Test
  @DisplayName(
      "the items are written to categoryoptiongroupsetdimension_items with a 0-based sort_order"
          + " and read back in that order")
  void testItemsKeepTheirOrder() {
    CategoryOptionGroupSetDimension dimension = persist(dimension(groupC, groupA, groupB));

    assertEquals(
        List.of(groupC.getId() + ":0", groupA.getId() + ":1", groupB.getId() + ":2"),
        itemRows(dimension));

    clearSessionAndSecondLevelCache();

    assertEquals(
        List.of(groupC.getUid(), groupA.getUid(), groupB.getUid()), itemUids(reload(dimension)));
  }

  @Test
  @DisplayName("setItems replaces the persisted items")
  void testSetItemsReplacesItems() {
    CategoryOptionGroupSetDimension dimension = persist(dimension(groupA, groupB));
    clearSessionAndSecondLevelCache();

    CategoryOptionGroupSetDimension loaded = reload(dimension);
    loaded.setItems(new ArrayList<>(List.of(groupC)));
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    assertEquals(List.of(groupC.getUid()), itemUids(reload(dimension)));
  }

  @Test
  @DisplayName("the dimension and the items are loaded lazily")
  void testAssociationsAreLazy() {
    ManyToOneType dimensionType =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("dimension"));

    assertFalse(dimensionType.isEager(null));
    assertTrue(itemsPersister().isLazy());
  }

  @Test
  @DisplayName(
      "the entity and its items are second-level cached with the nonstrict-read-write strategy")
  void testNonstrictReadWriteCaches() {
    EntityPersister persister = persister();
    CollectionPersister itemsPersister = itemsPersister();

    assertTrue(persister.canReadFromCache());
    assertEquals(
        AccessType.NONSTRICT_READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
    // a nonstrict-read-write collection access reports READ_WRITE from getAccessType() in
    // Hibernate 5.6, so the strategy is proven by the access implementation instead
    assertTrue(itemsPersister.hasCache());
    assertInstanceOf(
        CollectionNonStrictReadWriteAccess.class, itemsPersister.getCacheAccessStrategy());
  }

  @Test
  @DisplayName(
      "a visualization saves its category option group set dimensions by cascade and keeps their"
          + " order")
  void testVisualizationOwnsOrderedDimensions() {
    CategoryOptionGroupSetDimension first = dimension(groupB, groupA);
    CategoryOptionGroupSetDimension second = dimension(groupC);
    Visualization visualization = createVisualization('V');
    visualization.addCategoryOptionGroupSetDimension(first);
    visualization.addCategoryOptionGroupSetDimension(second);
    long visualizationId = visualizationService.save(visualization);
    clearSessionAndSecondLevelCache();

    List<CategoryOptionGroupSetDimension> reloaded =
        visualizationService
            .getVisualization(visualizationId)
            .getCategoryOptionGroupSetDimensions();
    assertEquals(
        List.of(List.of(groupB.getUid(), groupA.getUid()), List.of(groupC.getUid())),
        reloaded.stream().map(CategoryOptionGroupSetDimensionStoreTest::itemUids).toList());
  }

  /** Reloads must hit the database, not the second-level cache of the dimension or its items. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private SessionFactoryImplementor sessionFactory() {
    return entityManagerFactory.unwrap(SessionFactoryImplementor.class);
  }

  private EntityPersister persister() {
    return sessionFactory().getMetamodel().entityPersister(CategoryOptionGroupSetDimension.class);
  }

  private CollectionPersister itemsPersister() {
    return sessionFactory().getMetamodel().collectionPersister(ITEMS_ROLE);
  }

  private CategoryOptionGroupSetDimension dimension(CategoryOptionGroup... items) {
    CategoryOptionGroupSetDimension dimension = new CategoryOptionGroupSetDimension();
    dimension.setDimension(groupSet);
    dimension.setItems(new ArrayList<>(List.of(items)));
    return dimension;
  }

  private CategoryOptionGroupSetDimension persist(CategoryOptionGroupSetDimension dimension) {
    entityManager.persist(dimension);
    entityManager.flush();
    return dimension;
  }

  private CategoryOptionGroupSetDimension reload(CategoryOptionGroupSetDimension dimension) {
    return entityManager.find(CategoryOptionGroupSetDimension.class, dimension.getId());
  }

  /** The dimension's item rows as {@code categoryoptiongroupid:sort_order}, by sort_order. */
  private List<String> itemRows(CategoryOptionGroupSetDimension dimension) {
    return jdbcTemplate.queryForList(
        "select categoryoptiongroupid || ':' || sort_order from"
            + " categoryoptiongroupsetdimension_items where categoryoptiongroupsetdimensionid = ?"
            + " order by sort_order",
        String.class,
        dimension.getId());
  }

  private static List<String> itemUids(CategoryOptionGroupSetDimension dimension) {
    return dimension.getItems().stream().map(CategoryOptionGroup::getUid).toList();
  }
}
