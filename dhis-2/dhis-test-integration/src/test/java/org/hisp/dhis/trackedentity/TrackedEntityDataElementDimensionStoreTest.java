/**
 * Tests the persistence mapping of {@link TrackedEntityDataElementDimension} to the
 * trackedentitydataelementdimension table, and its use as the element of {@link
 * EventVisualization#getDataElementDimensions()}.
 */
@Transactional
class TrackedEntityDataElementDimensionStoreTest extends PostgresIntegrationTestBase {

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private EventVisualizationStore eventVisualizationStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private Program program;

  private ProgramStage programStage;

  private DataElement dataElementA;

  private DataElement dataElementB;

  private LegendSet legendSet;

  @BeforeEach
  void setUp() {
    program = createProgram('A');
    manager.save(program);
    programStage = createProgramStage('A', program);
    manager.save(programStage);
    dataElementA = createDataElement('A');
    dataElementB = createDataElement('B');
    manager.save(dataElementA);
    manager.save(dataElementB);
    legendSet = createLegendSet('A');
    manager.save(legendSet);
  }

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on hibernate_sequence, one nextval per id")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName(
      "the data element, legend set, program stage and filter are written to their columns and"
          + " read back from them")
  void testColumnsRoundTrip() {
    TrackedEntityDataElementDimension dimension =
        persist(
            new TrackedEntityDataElementDimension(
                dataElementA, legendSet, programStage, "GT:5;LT:10"));

    assertEquals(
        Map.of(
            "dataelementid", dataElementA.getId(),
            "legendsetid", legendSet.getId(),
            "programstageid", programStage.getId(),
            "filter", "GT:5;LT:10"),
        jdbcTemplate.queryForMap(
            "select dataelementid, legendsetid, programstageid, filter"
                + " from trackedentitydataelementdimension"
                + " where trackedentitydataelementdimensionid = ?",
            dimension.getId()));

    clearSessionAndSecondLevelCache();

    TrackedEntityDataElementDimension reloaded = reload(dimension);
    assertEquals(dimension.getId(), reloaded.getId());
    assertEquals(dataElementA.getUid(), reloaded.getDataElement().getUid());
    assertEquals(legendSet.getUid(), reloaded.getLegendSet().getUid());
    assertEquals(programStage.getUid(), reloaded.getProgramStage().getUid());
    assertEquals("GT:5;LT:10", reloaded.getFilter());
  }

  @Test
  @DisplayName("every association and the filter are optional")
  void testAllPropertiesAreNullable() {
    EntityPersister persister = persister();
    for (String property : List.of("dataElement", "legendSet", "programStage", "filter")) {
      assertTrue(
          persister
              .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)],
          property);
    }

    TrackedEntityDataElementDimension dimension =
        persist(new TrackedEntityDataElementDimension(null, null, null, null));
    clearSessionAndSecondLevelCache();

    TrackedEntityDataElementDimension reloaded = reload(dimension);
    assertNull(reloaded.getDataElement());
    assertNull(reloaded.getLegendSet());
    assertNull(reloaded.getProgramStage());
    assertNull(reloaded.getFilter());
  }

  @Test
  @DisplayName("the filter is mapped as text")
  void testFilterIsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("filter"));
  }

  @Test
  @DisplayName("the data element, legend set and program stage are loaded lazily")
  void testAssociationsAreLazy() {
    for (String property : List.of("dataElement", "legendSet", "programStage")) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
      assertFalse(type.isEager(null), property);
    }
  }

  @Test
  @DisplayName(
      "deleting a legend set clears it from the dimensions that reference it, through the deletion"
          + " handler's HQL on the TrackedEntityDataElementDimension entity name")
  void testDeletionHandlerHqlResolvesEntityName() {
    TrackedEntityDataElementDimension dimension =
        persist(new TrackedEntityDataElementDimension(dataElementA, legendSet, programStage, null));
    clearSessionAndSecondLevelCache();

    manager.delete(manager.get(LegendSet.class, legendSet.getUid()));
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    TrackedEntityDataElementDimension reloaded = reload(dimension);
    assertNull(reloaded.getLegendSet());
    assertEquals(dataElementA.getUid(), reloaded.getDataElement().getUid());
  }

  @Test
  @DisplayName(
      "an event visualization saves its data element dimensions by cascade and keeps their order")
  void testEventVisualizationOwnsOrderedDimensions() {
    EventVisualization eventVisualization = createEventVisualization('A', program);
    eventVisualization.addTrackedEntityDataElementDimension(
        new TrackedEntityDataElementDimension(dataElementB, null, programStage, "EQ:1"));
    eventVisualization.addTrackedEntityDataElementDimension(
        new TrackedEntityDataElementDimension(dataElementA, legendSet, null, null));
    eventVisualizationStore.save(eventVisualization);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    List<TrackedEntityDataElementDimension> reloaded =
        eventVisualizationStore.getByUid(eventVisualization.getUid()).getDataElementDimensions();
    assertEquals(
        List.of(dataElementB.getUid() + ":EQ:1", dataElementA.getUid() + ":null"),
        reloaded.stream().map(d -> d.getDataElement().getUid() + ":" + d.getFilter()).toList());
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(TrackedEntityDataElementDimension.class);
  }

  private TrackedEntityDataElementDimension persist(TrackedEntityDataElementDimension dimension) {
    entityManager.persist(dimension);
    entityManager.flush();
    return dimension;
  }

  private TrackedEntityDataElementDimension reload(TrackedEntityDataElementDimension dimension) {
    return entityManager.find(TrackedEntityDataElementDimension.class, dimension.getId());
  }
}
