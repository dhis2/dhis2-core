package org.hisp.dhis.reservedvalue.hibernate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.sql.Timestamp;
import java.util.Date;
import java.util.List;
import java.util.Map;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.NoopOptimizer;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hisp.dhis.common.Objects;
import org.hisp.dhis.reservedvalue.ReservedValue;
import org.hisp.dhis.reservedvalue.ReservedValueStore;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the persistence mapping of {@link ReservedValue} to the reservedvalue table. */
@Transactional
class ReservedValueStoreTest extends PostgresIntegrationTestBase {

  private static final Date CREATED = new Date(1_700_000_000_000L);

  private static final Date EXPIRY_DATE = new Date(1_800_000_000_000L);

  @Autowired private ReservedValueStore reservedValueStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on reservedvalue_sequence, one nextval per id")
  void testIdGeneratorUsesReservedValueSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "reservedvalue_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName("all properties are written to their columns and read back")
  void testColumnsRoundTrip() {
    ReservedValue reservedValue = save(reservedValue("ownerUidA", "RANDOM(###)", "123"));

    assertEquals(
        Map.of(
            "ownerobject",
            Objects.TRACKEDENTITYATTRIBUTE.name(),
            "owneruid",
            "ownerUidA",
            "key",
            "RANDOM(###)",
            "value",
            "123",
            "created",
            new Timestamp(CREATED.getTime()),
            "expirydate",
            new Timestamp(EXPIRY_DATE.getTime())),
        jdbcTemplate.queryForMap(
            "select ownerobject, owneruid, key, value, created, expirydate from reservedvalue"
                + " where reservedvalueid = ?",
            reservedValue.getId()));

    clearSession();

    ReservedValue reloaded = entityManager.find(ReservedValue.class, reservedValue.getId());
    assertEquals(Objects.TRACKEDENTITYATTRIBUTE.name(), reloaded.getOwnerObject());
    assertEquals("ownerUidA", reloaded.getOwnerUid());
    assertEquals("RANDOM(###)", reloaded.getKey());
    assertEquals("123", reloaded.getValue());
    assertEquals(CREATED.getTime(), reloaded.getCreated().getTime());
    assertEquals(EXPIRY_DATE.getTime(), reloaded.getExpiryDate().getTime());
  }

  @Test
  @DisplayName("created and expiryDate are mapped not-null, the owner, key and value nullable")
  void testNullability() {
    EntityPersister persister = persister();
    boolean[] nullable = persister.getPropertyNullability();

    assertFalse(nullable[persister.getEntityMetamodel().getPropertyIndex("created")]);
    assertFalse(nullable[persister.getEntityMetamodel().getPropertyIndex("expiryDate")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("ownerObject")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("ownerUid")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("key")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("value")]);
  }

  @Test
  @DisplayName("the tracked entity attribute id is not mapped")
  void testTrackedEntityAttributeIdIsNotMapped() {
    assertFalse(
        List.of(persister().getPropertyNames()).contains("trackedEntityAttributeId"),
        "trackedEntityAttributeId must stay in-memory only");
  }

  /**
   * The tracked entity attribute value branch and the store's call path are covered by {@link
   * HibernateReservedValueStoreTest}.
   */
  @Test
  @DisplayName(
      "the named native query returns the lower-cased requested values reserved for the owner and"
          + " key")
  void testNotAvailableValuesNamedQueryReturnsReservedValues() {
    save(reservedValue("ownerUidA", "RANDOM(###)", "ABC"));
    save(reservedValue("ownerUidA", "OTHER(###)", "DEF"));
    save(reservedValue("ownerUidB", "RANDOM(###)", "GHI"));
    clearSession();

    List<?> result =
        entityManager
            .createNamedQuery(ReservedValue.NOT_AVAILABLE_VALUES_QUERY)
            .setParameter("teaId", -1L)
            .setParameter("ownerObject", Objects.TRACKEDENTITYATTRIBUTE.name())
            .setParameter("ownerUid", "ownerUidA")
            .setParameter("key", "RANDOM(###)")
            .setParameter("values", List.of("abc", "def", "ghi", "jkl"))
            .getResultList();

    assertEquals(List.of("abc"), result);
  }

  @Test
  @DisplayName("counting used values counts only the rows of the owner uid and key")
  void testGetNumberOfUsedValuesCountsRowsOfOwnerAndKey() {
    save(reservedValue("ownerUidA", "RANDOM(###)", "1"));
    save(reservedValue("ownerUidA", "RANDOM(###)", "2"));
    save(reservedValue("ownerUidA", "OTHER(###)", "3"));
    save(reservedValue("ownerUidB", "RANDOM(###)", "4"));
    clearSession();

    ReservedValue query =
        ReservedValue.builder()
            .ownerObject(Objects.DATAELEMENT.name())
            .ownerUid("ownerUidA")
            .key("RANDOM(###)")
            .build();

    assertEquals(2, reservedValueStore.getNumberOfUsedValues(query));
  }

  @Test
  @DisplayName("deleting by owner uid removes only that owner's rows")
  void testDeleteReservedValueByUid() {
    ReservedValue deleted = save(reservedValue("ownerUidA", "RANDOM(###)", "1"));
    ReservedValue kept = save(reservedValue("ownerUidB", "RANDOM(###)", "1"));
    clearSession();

    reservedValueStore.deleteReservedValueByUid("ownerUidA");
    clearSession();

    assertNull(entityManager.find(ReservedValue.class, deleted.getId()));
    assertNotNull(entityManager.find(ReservedValue.class, kept.getId()));
  }

  private ReservedValue save(ReservedValue reservedValue) {
    reservedValueStore.save(reservedValue);
    entityManager.flush();
    return reservedValue;
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ReservedValue.class);
  }

  private static ReservedValue reservedValue(String ownerUid, String key, String value) {
    return ReservedValue.builder()
        .ownerObject(Objects.TRACKEDENTITYATTRIBUTE.name())
        .ownerUid(ownerUid)
        .key(key)
        .value(value)
        .created(CREATED)
        .expiryDate(EXPIRY_DATE)
        .build();
  }
}
