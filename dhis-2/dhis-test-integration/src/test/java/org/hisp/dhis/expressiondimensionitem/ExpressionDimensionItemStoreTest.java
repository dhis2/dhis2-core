/**
 * Tests the persistence mapping of {@link ExpressionDimensionItem} to the expressiondimensionitem
 * table.
 */
@Transactional
class ExpressionDimensionItemStoreTest extends PostgresIntegrationTestBase {

  private static final String ATTRIBUTE_UID = "AttrUid0001";

  @Autowired
  @Qualifier("org.hisp.dhis.expressiondimensionitem.ExpressionDimensionItemStore")
  private IdentifiableObjectStore<ExpressionDimensionItem> store;

  @Autowired private AnalyticalObjectStore<Visualization> visualizationStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() {
    User admin = getAdminUser();
    ExpressionDimensionItem item =
        new ExpressionDimensionItem(
            "#{fbfJHSPpUQD}+#{cYeuwXTCPkU}", "Sum of two", MissingValueStrategy.NEVER_SKIP);
    item.setCode("CODE_EDI");
    item.setName("Expression A");
    item.setShortName("Expr A");
    item.setFormName("Expression form A");
    item.setSlidingWindow(true);
    item.setLastUpdatedBy(admin);
    item.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Expression fr")));
    item.setAttributeValues(AttributeValues.of(Map.of(ATTRIBUTE_UID, "attribute value")));
    item.getSharing().setPublicAccess("rw------");
    ExpressionDimensionItem saved = save(item);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, shortname, formname, description, expression,"
                + " missingvaluestrategy, slidingwindow, translations::text as translations,"
                + " attributevalues::text as attributevalues, sharing->>'public' as publicaccess"
                + " from expressiondimensionitem where expressiondimensionitemid = ?",
            saved.getId());
    assertEquals("CODE_EDI", row.get("code"));
    assertEquals("Expression A", row.get("name"));
    assertEquals("Expr A", row.get("shortname"));
    assertEquals("Expression form A", row.get("formname"));
    assertEquals("Sum of two", row.get("description"));
    assertEquals("#{fbfJHSPpUQD}+#{cYeuwXTCPkU}", row.get("expression"));
    assertEquals("NEVER_SKIP", row.get("missingvaluestrategy"));
    assertEquals(Boolean.TRUE, row.get("slidingwindow"));
    assertTrue(((String) row.get("translations")).contains("\"Expression fr\""));
    assertTrue(((String) row.get("attributevalues")).contains("\"attribute value\""));
    assertEquals("rw------", row.get("publicaccess"));

    ExpressionDimensionItem reloaded = reload(saved);
    assertEquals("CODE_EDI", reloaded.getCode());
    assertEquals("Expression A", reloaded.getName());
    assertEquals("Expr A", reloaded.getShortName());
    assertEquals("Expression form A", reloaded.getFormName());
    assertEquals("Sum of two", reloaded.getDescription());
    assertEquals("#{fbfJHSPpUQD}+#{cYeuwXTCPkU}", reloaded.getExpression());
    assertEquals(MissingValueStrategy.NEVER_SKIP, reloaded.getMissingValueStrategy());
    assertTrue(reloaded.getSlidingWindow());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Expression fr")),
        reloaded.getTranslations());
    assertEquals("attribute value", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(admin.getUid(), reloaded.getCreatedBy().getUid());
  }

  @Test
  @DisplayName("null translations, attributevalues and sharing columns load as empty values")
  void testNullJsonbColumnsLoadAsEmptyValues() {
    ExpressionDimensionItem saved = save(item("Null jsonb"));
    jdbcTemplate.update(
        "update expressiondimensionitem set translations = null, attributevalues = null,"
            + " sharing = null where expressiondimensionitemid = ?",
        saved.getId());

    ExpressionDimensionItem reloaded = reload(saved);
    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals("Null jsonb", reloaded.getDisplayName());
    assertTrue(reloaded.getAttributeValues().isEmpty());
    assertNull(reloaded.getSharing().getPublicAccess());
    reloaded.addAttributeValue(ATTRIBUTE_UID, "added");
    assertEquals("added", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
  }

  @Test
  @DisplayName("an item without translations is written with an empty translations array")
  void testNullTranslationsAreWrittenAsEmptyArray() {
    ExpressionDimensionItem item = item("No translations");
    item.setTranslations(null);
    ExpressionDimensionItem saved = save(item);

    assertEquals(
        "[]",
        jdbcTemplate.queryForObject(
            "select translations::text from expressiondimensionitem"
                + " where expressiondimensionitemid = ?",
            String.class,
            saved.getId()));
  }

  @Test
  @DisplayName("description and expression are bound as text")
  void testTextColumns() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
    assertInstanceOf(TextType.class, persister().getPropertyType("expression"));
  }

  @Test
  @DisplayName("translations, sharing and attributeValues use their jsonb user types")
  void testJsonbTypes() {
    ComponentType component =
        assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    CustomType translations = assertInstanceOf(CustomType.class, component.getSubtypes()[0]);
    CustomType sharing = assertInstanceOf(CustomType.class, persister().getPropertyType("sharing"));
    CustomType attributeValues =
        assertInstanceOf(CustomType.class, persister().getPropertyType("attributeValues"));

    assertInstanceOf(JsonSetBinaryType.class, translations.getUserType());
    assertInstanceOf(SharingJsonBinaryType.class, sharing.getUserType());
    assertInstanceOf(JsonAttributeValuesBinaryType.class, attributeValues.getUserType());
  }

  @Test
  @DisplayName("createdBy and lastUpdatedBy are lazy many-to-ones")
  void testUserReferencesAreLazy() {
    assertFalse(manyToOne("createdBy").isEager(null));
    assertFalse(manyToOne("lastUpdatedBy").isEager(null));
  }

  @Test
  @DisplayName("name and shortName are mapped not-null, the item's other columns nullable")
  void testNullability() {
    assertNotNullable("name");
    assertNotNullable("shortName");
    assertNullable("code");
    assertNullable("formName");
    assertNullable("description");
    assertNullable("expression");
    assertNullable("slidingWindow");
    assertNullable("missingValueStrategy");
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void testCacheStrategy() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("the item's columns are mapped and the analytics-only state is not mapped")
  void testPersistedAndTransientProperties() {
    EntityMetamodel metamodel = persister().getEntityMetamodel();
    for (String property :
        List.of(
            "code",
            "name",
            "shortName",
            "formName",
            "description",
            "translations",
            "expression",
            "slidingWindow",
            "missingValueStrategy",
            "attributeValues",
            "sharing")) {
      assertNotNull(metamodel.getPropertyIndexOrNull(property), property);
    }
    for (String property :
        List.of(
            "queryMods",
            "legendSets",
            "aggregationType",
            "aggregateExportCategoryOptionCombo",
            "aggregateExportAttributeOptionCombo")) {
      assertNull(metamodel.getPropertyIndexOrNull(property), property);
    }
  }

  @Test
  @DisplayName("a visualization data dimension item references the item and is found by it")
  void testVisualizationReferencesItem() {
    ExpressionDimensionItem item = save(item("In visualization"));
    Visualization visualization = createVisualization('A');
    visualization.addDataDimensionItem(item);
    visualizationStore.save(visualization);
    entityManager.flush();

    assertEquals(
        item.getId(),
        jdbcTemplate.queryForObject(
            "select expressiondimensionitemid from datadimensionitem"
                + " where datadimensionitemid = ?",
            Long.class,
            visualization.getDataDimensionItems().get(0).getId()));
    clearSession();
    entityManagerFactory.getCache().evict(ExpressionDimensionItem.class);

    ExpressionDimensionItem reloaded = store.get(item.getId());
    List<Visualization> visualizations = visualizationStore.getAnalyticalObjects(reloaded);
    assertEquals(
        List.of(visualization.getUid()),
        visualizations.stream().map(Visualization::getUid).toList());
    assertEquals(
        "In visualization",
        visualizations
            .get(0)
            .getDataDimensionItems()
            .get(0)
            .getExpressionDimensionItem()
            .getName());
  }

  private ExpressionDimensionItem item(String name) {
    ExpressionDimensionItem item = new ExpressionDimensionItem("#{fbfJHSPpUQD}", null);
    item.setName(name);
    item.setShortName(name);
    return item;
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ExpressionDimensionItem.class);
  }

  private ManyToOneType manyToOne(String property) {
    return assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  /** Saves without resetting the sharing, so a preset public access is kept. */
  private ExpressionDimensionItem save(ExpressionDimensionItem item) {
    store.save(item, false);
    entityManager.flush();
    return item;
  }

  /** Reloads the item from the database, bypassing the session and the second-level cache. */
  private ExpressionDimensionItem reload(ExpressionDimensionItem item) {
    clearSession();
    entityManagerFactory.getCache().evict(ExpressionDimensionItem.class);
    return store.get(item.getId());
  }
}
