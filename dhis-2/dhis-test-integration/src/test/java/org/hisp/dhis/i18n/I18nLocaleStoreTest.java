package org.hisp.dhis.i18n;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.util.Date;
import java.util.List;
import java.util.Map;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.tuple.entity.EntityMetamodel;
import org.hibernate.type.ManyToOneType;
import org.hisp.dhis.common.Locale;
import org.hisp.dhis.i18n.locale.I18nLocale;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.hisp.dhis.user.User;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the persistence mapping of {@link I18nLocale} to the i18nlocale table. */
@Transactional
class I18nLocaleStoreTest extends PostgresIntegrationTestBase {

  @Autowired private I18nLocaleStore store;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() {
    User admin = getAdminUser();
    I18nLocale locale = new I18nLocale(new Locale("fr", "FR"));
    locale.setCode("CODE_FR_FR");
    locale.setLastUpdatedBy(admin);
    I18nLocale saved = save(locale);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, locale, created, lastupdated, lastupdatedby"
                + " from i18nlocale where i18nlocaleid = ?",
            saved.getId());
    assertEquals(saved.getUid(), row.get("uid"));
    assertEquals("CODE_FR_FR", row.get("code"));
    assertEquals("French (France)", row.get("name"));
    assertEquals("fr_FR", row.get("locale"));
    assertEquals(saved.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(saved.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(admin.getId(), ((Number) row.get("lastupdatedby")).longValue());

    clearSession();

    I18nLocale reloaded = store.get(saved.getId());
    assertEquals(saved.getUid(), reloaded.getUid());
    assertEquals("CODE_FR_FR", reloaded.getCode());
    assertEquals("French (France)", reloaded.getName());
    assertEquals("fr_FR", reloaded.getLocale());
    assertEquals(saved.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(saved.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(admin.getUid(), reloaded.getLastUpdatedBy().getUid());
  }

  @Test
  @DisplayName("lastUpdatedBy is a lazy many-to-one")
  void testLastUpdatedByIsLazy() {
    ManyToOneType type =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("lastUpdatedBy"));

    assertFalse(type.isEager(null));
  }

  @Test
  @DisplayName("uid, name, locale, created and lastUpdated are mapped not-null")
  void testNullability() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] nullability = persister.getPropertyNullability();

    assertFalse(nullability[metamodel.getPropertyIndex("uid")]);
    assertFalse(nullability[metamodel.getPropertyIndex("name")]);
    assertFalse(nullability[metamodel.getPropertyIndex("locale")]);
    assertFalse(nullability[metamodel.getPropertyIndex("created")]);
    assertFalse(nullability[metamodel.getPropertyIndex("lastUpdated")]);
    assertTrue(nullability[metamodel.getPropertyIndex("code")]);
    assertTrue(nullability[metamodel.getPropertyIndex("lastUpdatedBy")]);
  }

  @Test
  @DisplayName("created is not updatable")
  void testCreatedIsNotUpdatable() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] updateability = persister.getPropertyUpdateability();

    assertFalse(updateability[metamodel.getPropertyIndex("created")]);
    assertTrue(updateability[metamodel.getPropertyIndex("lastUpdated")]);
  }

  @Test
  @DisplayName("the entity is not second-level cached")
  void testNotCached() {
    assertFalse(persister().canReadFromCache());
  }

  @Test
  @DisplayName("only the mapped properties are persisted")
  void testMappedProperties() {
    assertEquals(
        List.of("code", "created", "lastUpdated", "lastUpdatedBy", "locale", "name", "uid"),
        List.of(persister().getPropertyNames()).stream().sorted().toList());
  }

  @Test
  @DisplayName("saving through the store succeeds although createdBy and sharing are not mapped")
  void testStoreSaveIgnoresUnmappedProperties() {
    I18nLocale saved = save(new I18nLocale(new Locale("es")));
    clearSession();

    I18nLocale reloaded = store.get(saved.getId());
    assertNull(reloaded.getCreatedBy());
    assertNull(reloaded.getSharing().getOwner());
  }

  @Test
  @DisplayName("a locale is found by its locale column")
  void testGetI18nLocaleByLocale() {
    I18nLocale saved = save(new I18nLocale(new Locale("pt", "BR")));
    save(new I18nLocale(new Locale("pt")));
    clearSession();

    assertEquals(saved.getUid(), store.getI18nLocaleByLocale(new Locale("pt", "BR")).getUid());
    assertNull(store.getI18nLocaleByLocale(new Locale("pt", "PT")));
  }

  @Test
  @DisplayName("updating a loaded locale is persisted")
  void testUpdate() {
    I18nLocale saved = save(new I18nLocale(new Locale("nl")));
    clearSession();

    I18nLocale loaded = store.get(saved.getId());
    loaded.setName("Nederlands");
    loaded.setCode("CODE_NL");
    store.update(loaded);
    entityManager.flush();
    clearSession();

    I18nLocale reloaded = store.get(saved.getId());
    assertEquals("Nederlands", reloaded.getName());
    assertEquals("CODE_NL", reloaded.getCode());
  }

  @Test
  @DisplayName("deleting a locale removes only its row")
  void testDelete() {
    I18nLocale deleted = save(new I18nLocale(new Locale("sv")));
    I18nLocale kept = save(new I18nLocale(new Locale("nb")));

    store.delete(store.get(deleted.getId()));
    entityManager.flush();
    clearSession();

    assertNull(store.get(deleted.getId()));
    assertEquals(kept.getUid(), store.get(kept.getId()).getUid());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(I18nLocale.class);
  }

  private I18nLocale save(I18nLocale locale) {
    store.save(locale);
    entityManager.flush();
    return locale;
  }
}
