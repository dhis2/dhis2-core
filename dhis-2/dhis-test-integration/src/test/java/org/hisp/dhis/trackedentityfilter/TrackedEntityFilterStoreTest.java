@Transactional
class TrackedEntityFilterStoreTest extends PostgresIntegrationTestBase {
  @Autowired private TrackedEntityFilterStore store;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private Program programA;

  private Program programB;

  @BeforeEach
  void setUp() {
    programA = createProgram('A');
    manager.save(programA);
    programB = createProgram('B');
    manager.save(programB);
  }

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void shouldWriteAndReadBackEveryMappedColumn() {
    User admin = getAdminUser();
    TrackedEntityFilter filter = createFilter("Filter A", programA);
    filter.setCode("TEF_A");
    filter.setDescription("Description A");
    filter.setSortOrder(7);
    filter.setStyle(style("#ff0000", "icon-a"));
    filter.setEventFilters(List.of(eventFilter("StageUid0A")));
    filter.getEntityQueryCriteria().setOrder("createdAt:desc");
    filter.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Filtre A")));
    filter.getSharing().setPublicAccess("rw------");
    filter.getSharing().setOwner(admin.getUid());
    store.save(filter, false);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, description, sortorder, programid,"
                + " style->>'color' as color, style->>'icon' as icon,"
                + " eventfilters->0->>'programStage' as eventstage,"
                + " entityquerycriteria->>'order' as criteriaorder,"
                + " translations::text as translations,"
                + " sharing->>'public' as publicaccess, sharing->>'owner' as owner"
                + " from trackedentityfilter where trackedentityfilterid = ?",
            filter.getId());
    assertEquals("TEF_A", row.get("code"));
    assertEquals("Filter A", row.get("name"));
    assertEquals("Description A", row.get("description"));
    assertEquals(7, ((Number) row.get("sortorder")).intValue());
    assertEquals(programA.getId(), ((Number) row.get("programid")).longValue());
    assertEquals("#ff0000", row.get("color"));
    assertEquals("icon-a", row.get("icon"));
    assertEquals("StageUid0A", row.get("eventstage"));
    assertEquals("createdAt:desc", row.get("criteriaorder"));
    assertTrue(((String) row.get("translations")).contains("\"Filtre A\""));
    assertEquals("rw------", row.get("publicaccess"));
    assertEquals(admin.getUid(), row.get("owner"));

    TrackedEntityFilter reloaded = reload(filter);
    assertEquals("TEF_A", reloaded.getCode());
    assertEquals("Filter A", reloaded.getName());
    assertEquals("Description A", reloaded.getDescription());
    assertEquals(7, reloaded.getSortOrder());
    assertEquals(programA.getUid(), reloaded.getProgram().getUid());
    assertEquals("#ff0000", reloaded.getStyle().getColor());
    assertEquals("icon-a", reloaded.getStyle().getIcon());
    assertEquals(1, reloaded.getEventFilters().size());
    assertEquals("StageUid0A", reloaded.getEventFilters().get(0).getProgramStage());
    assertEquals("createdAt:desc", reloaded.getEntityQueryCriteria().getOrder());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Filtre A")), reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(admin.getUid(), reloaded.getSharing().getOwner());
  }

  @Test
  @DisplayName("the whole entity query criteria and event filters are stored and read back")
  void shouldStoreAndReadBackWholeCriteriaAndEventFilters() throws JsonProcessingException {
    TrackedEntityFilter filter = createFilter("Filter B", programA);
    EntityQueryCriteria criteria = createFullCriteria();
    filter.setEntityQueryCriteria(criteria);
    List<EventFilter> eventFilters = List.of(eventFilter("StageUid0A"), eventFilter("StageUid0B"));
    filter.setEventFilters(eventFilters);
    TrackedEntityFilter saved = save(filter);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select entityquerycriteria->'attributeValueFilters'->0->>'attribute' as attr,"
                + " entityquerycriteria->'enrollmentCreatedDate'->>'startBuffer' as startbuffer,"
                + " entityquerycriteria->>'followUp' as followup,"
                + " jsonb_array_length(eventfilters) as eventfiltercount"
                + " from trackedentityfilter where trackedentityfilterid = ?",
            saved.getId());
    assertEquals("TeaUid00001", row.get("attr"));
    assertEquals("-5", row.get("startbuffer"));
    assertEquals("true", row.get("followup"));
    assertEquals(2, ((Number) row.get("eventfiltercount")).intValue());

    TrackedEntityFilter reloaded = reload(saved);

    ObjectMapper mapper = new ObjectMapper();
    assertEquals(
        mapper.writeValueAsString(criteria),
        mapper.writeValueAsString(reloaded.getEntityQueryCriteria()));
    assertEquals(
        mapper.writeValueAsString(eventFilters),
        mapper.writeValueAsString(reloaded.getEventFilters()));
    assertEquals(
        EnrollmentStatus.COMPLETED, reloaded.getEntityQueryCriteria().getEnrollmentStatus());
    assertEquals(
        new Date(1_700_000_000_000L),
        reloaded.getEntityQueryCriteria().getEventDate().getStartDate());
    assertEquals(EventStatus.SCHEDULE, reloaded.getEventFilters().get(1).getEventStatus());
  }

  @Test
  @DisplayName("the jsonb properties are bound to their typedefs")
  void shouldBindJsonbPropertiesToTheirTypedefs() {
    assertJsonType(JsonBinaryType.class, ObjectStyle.class, "style");
    assertJsonType(JsonListBinaryType.class, EventFilter.class, "eventFilters");
    assertJsonType(JsonBinaryType.class, EntityQueryCriteria.class, "entityQueryCriteria");
    assertInstanceOf(
        SharingJsonBinaryType.class,
        assertInstanceOf(CustomType.class, persister().getPropertyType("sharing")).getUserType());
  }

  @Test
  @DisplayName("description is bound as a plain string, as its column is varchar(255)")
  void shouldBindDescriptionAsString() {
    assertInstanceOf(StringType.class, persister().getPropertyType("description"));
  }

  @Test
  @DisplayName("program is an eager many-to-one fetched by a separate select")
  void shouldFetchProgramEagerlyBySelect() {
    AbstractEntityPersister persister = (AbstractEntityPersister) persister();
    int index = persister.getEntityMetamodel().getPropertyIndex("program");

    assertTrue(
        assertInstanceOf(ManyToOneType.class, persister.getPropertyType("program")).isEager(null));
    assertEquals(org.hibernate.FetchMode.SELECT, persister.getFetchMode(index));
  }

  @Test
  @DisplayName("name and program are mapped not-null, the other own properties nullable")
  void shouldMapNameAndProgramNotNull() {
    assertNotNullable("name");
    assertNotNullable("program");
    assertNullable("code");
    assertNullable("description");
    assertNullable("style");
    assertNullable("eventFilters");
    assertNullable("entityQueryCriteria");
    assertNullable("sharing");
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("filters are found by their program")
  void shouldGetFiltersByProgram() {
    TrackedEntityFilter filterA = save(createFilter("Filter A", programA));
    TrackedEntityFilter filterB = save(createFilter("Filter B", programB));
    clearSession();

    List<TrackedEntityFilter> filters = store.get(programA);

    assertEquals(
        List.of(filterA.getUid()), filters.stream().map(TrackedEntityFilter::getUid).toList());
    assertEquals(
        List.of(filterB.getUid()),
        store.get(programB).stream().map(TrackedEntityFilter::getUid).toList());
  }

  @Test
  @DisplayName("a null translations column is read as no translations")
  void shouldReadNullTranslationsColumnAsEmpty() {
    TrackedEntityFilter saved = save(createFilter("Filter C", programA));
    jdbcTemplate.update(
        "update trackedentityfilter set translations = null where trackedentityfilterid = ?",
        saved.getId());

    TrackedEntityFilter reloaded = reload(saved);

    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals("Filter C", reloaded.getDisplayName());
  }

  @Test
  @DisplayName("a null sharing column is read as empty sharing")
  void shouldReadNullSharingColumnAsEmptySharing() {
    TrackedEntityFilter saved = save(createFilter("Filter D", programA));
    jdbcTemplate.update(
        "update trackedentityfilter set sharing = null where trackedentityfilterid = ?",
        saved.getId());

    TrackedEntityFilter reloaded = reload(saved);

    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
  }

  private TrackedEntityFilter createFilter(String name, Program program) {
    TrackedEntityFilter filter = new TrackedEntityFilter();
    filter.setAutoFields();
    filter.setName(name);
    filter.setProgram(program);
    filter.setEntityQueryCriteria(new EntityQueryCriteria());
    return filter;
  }

  private static ObjectStyle style(String color, String icon) {
    ObjectStyle style = new ObjectStyle();
    style.setColor(color);
    style.setIcon(icon);
    return style;
  }

  private static EventFilter eventFilter(String programStage) {
    FilterPeriod period = new FilterPeriod();
    period.setPeriodFrom(-10);
    period.setPeriodTo(10);

    EventFilter eventFilter = new EventFilter();
    eventFilter.setProgramStage(programStage);
    eventFilter.setEventStatus(EventStatus.SCHEDULE);
    eventFilter.setEventCreatedPeriod(period);
    eventFilter.setAssignedUserMode(AssignedUserSelectionMode.PROVIDED);
    eventFilter.setAssignedUsers(Set.of("UserUid0001"));
    return eventFilter;
  }

  private static EntityQueryCriteria createFullCriteria() {
    AttributeValueFilter attributeFilter = new AttributeValueFilter();
    attributeFilter.setAttribute("TeaUid00001");
    attributeFilter.setEq("v");
    attributeFilter.setNull(true);

    DateFilterPeriod buffers = new DateFilterPeriod();
    buffers.setType(DatePeriodType.RELATIVE);
    buffers.setStartBuffer(-5);
    buffers.setEndBuffer(5);

    EntityQueryCriteria criteria = new EntityQueryCriteria();
    criteria.setProgramStage("StageUid0A");
    criteria.setFollowUp(true);
    criteria.setOrganisationUnit("OrgUnit0001");
    criteria.setOuMode(OrganisationUnitSelectionMode.SELECTED);
    criteria.setAssignedUserMode(AssignedUserSelectionMode.PROVIDED);
    criteria.setAssignedUsers(Set.of("UserUid0001"));
    criteria.setOrder("createdAt:desc");
    criteria.setDisplayColumnOrder(List.of("colA", "colB"));
    criteria.setTrackedEntities(Set.of("TeUid000001"));
    criteria.setTrackedEntityType("TetUid00001");
    criteria.setEventStatus(EventStatus.ACTIVE);
    criteria.setEnrollmentStatus(EnrollmentStatus.COMPLETED);
    criteria.setEventDate(absolute());
    criteria.setLastUpdatedDate(relative(RelativePeriodEnum.LAST_WEEK));
    criteria.setEnrollmentIncidentDate(relative(RelativePeriodEnum.THIS_YEAR));
    criteria.setEnrollmentCreatedDate(buffers);
    criteria.setAttributeValueFilters(List.of(attributeFilter));
    return criteria;
  }

  private static DateFilterPeriod relative(RelativePeriodEnum period) {
    DateFilterPeriod filter = new DateFilterPeriod();
    filter.setType(DatePeriodType.RELATIVE);
    filter.setPeriod(period);
    return filter;
  }

  private static DateFilterPeriod absolute() {
    DateFilterPeriod filter = new DateFilterPeriod();
    filter.setType(DatePeriodType.ABSOLUTE);
    filter.setStartDate(new Date(1_700_000_000_000L));
    filter.setEndDate(new Date(1_710_000_000_000L));
    return filter;
  }

  private void assertJsonType(Class<?> typeClass, Class<?> returnedClass, String property) {
    CustomType type = assertInstanceOf(CustomType.class, persister().getPropertyType(property));
    assertEquals(typeClass, type.getUserType().getClass(), property);
    assertEquals(returnedClass, ((JsonBinaryType) type.getUserType()).returnedClass(), property);
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(TrackedEntityFilter.class);
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private TrackedEntityFilter save(TrackedEntityFilter filter) {
    store.save(filter);
    entityManager.flush();
    return filter;
  }

  /** Reloads the filter from the database, bypassing the session and the L2 cache. */
  private TrackedEntityFilter reload(TrackedEntityFilter filter) {
    clearSession();
    entityManagerFactory.getCache().evict(TrackedEntityFilter.class);
    return store.get(filter.getId());
  }
}
