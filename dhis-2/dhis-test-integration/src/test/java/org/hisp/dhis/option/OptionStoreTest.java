/** Tests the persistence mapping of {@link Option} to the optionvalue table. */
@Transactional
class OptionStoreTest extends PostgresIntegrationTestBase {

  private static final String ATTRIBUTE_UID = "AttrUid0001";

  @Autowired private OptionStore store;

  @Autowired private OptionService optionService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() throws ConflictException {
    OptionSet optionSet = saveOptionSet("Colours");
    Option option = new Option("Red", "RED", 1);
    option.setDescription("The colour red");
    option.setFormName("Red form name");
    option.setStyle(style("#ff0000", "red-icon"));
    option.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Rouge")));
    option.setAttributeValues(AttributeValues.of(Map.of(ATTRIBUTE_UID, "attribute value")));
    option.setOptionSet(optionSet);
    store.save(option);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, created, lastupdated, sort_order, description, formname,"
                + " style->>'color' as color, style->>'icon' as icon,"
                + " translations::text as translations, attributevalues::text as attributevalues,"
                + " optionsetid from optionvalue where optionvalueid = ?",
            option.getId());
    assertEquals(option.getUid(), row.get("uid"));
    assertEquals("RED", row.get("code"));
    assertEquals("Red", row.get("name"));
    assertEquals(option.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(option.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(1, row.get("sort_order"));
    assertEquals("The colour red", row.get("description"));
    assertEquals("Red form name", row.get("formname"));
    assertEquals("#ff0000", row.get("color"));
    assertEquals("red-icon", row.get("icon"));
    assertTrue(((String) row.get("translations")).contains("\"Rouge\""));
    assertTrue(((String) row.get("attributevalues")).contains("\"attribute value\""));
    assertEquals(optionSet.getId(), ((Number) row.get("optionsetid")).longValue());

    Option reloaded = reload(option);
    assertEquals(option.getUid(), reloaded.getUid());
    assertEquals("RED", reloaded.getCode());
    assertEquals("Red", reloaded.getName());
    assertEquals(option.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(option.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(1, reloaded.getSortOrder());
    assertEquals("The colour red", reloaded.getDescription());
    assertEquals("Red form name", reloaded.getFormName());
    assertEquals(style("#ff0000", "red-icon"), reloaded.getStyle());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Rouge")), reloaded.getTranslations());
    assertEquals("attribute value", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
    assertEquals(optionSet.getUid(), reloaded.getOptionSet().getUid());
  }

  @Test
  @DisplayName("a null attributevalues column loads as empty attribute values")
  void testNullAttributeValuesLoadAsEmpty() throws ConflictException {
    OptionSet optionSet = saveOptionSet("Sizes", new Option("Small", "S", 1));
    Option option = optionSet.getOptions().get(0);
    jdbcTemplate.update(
        "update optionvalue set attributevalues = null where optionvalueid = ?", option.getId());

    Option reloaded = reload(option);
    assertTrue(reloaded.getAttributeValues().isEmpty());
    reloaded.addAttributeValue(ATTRIBUTE_UID, "added");
    assertEquals("added", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
  }

  @Test
  @DisplayName("description and formName are bound as text")
  void testTextColumns() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
    assertInstanceOf(TextType.class, persister().getPropertyType("formName"));
  }

  @Test
  @DisplayName("style, translations and attributeValues use their jsonb user types")
  void testJsonbTypes() {
    CustomType style = assertInstanceOf(CustomType.class, persister().getPropertyType("style"));
    ComponentType component =
        assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    CustomType translations = assertInstanceOf(CustomType.class, component.getSubtypes()[0]);
    CustomType attributeValues =
        assertInstanceOf(CustomType.class, persister().getPropertyType("attributeValues"));

    JsonBinaryType styleType = assertInstanceOf(JsonBinaryType.class, style.getUserType());
    assertEquals(ObjectStyle.class, styleType.returnedClass());
    assertInstanceOf(JsonSetBinaryType.class, translations.getUserType());
    assertInstanceOf(JsonAttributeValuesBinaryType.class, attributeValues.getUserType());
  }

  @Test
  @DisplayName("optionSet is a lazy many-to-one")
  void testOptionSetIsLazy() {
    ManyToOneType optionSet =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("optionSet"));

    assertFalse(optionSet.isEager(null));
  }

  @Test
  @DisplayName("uid, code, name, created and lastUpdated are mapped not-null")
  void testNullability() {
    assertFalse(isNullable("uid"));
    assertFalse(isNullable("code"));
    assertFalse(isNullable("name"));
    assertFalse(isNullable("created"));
    assertFalse(isNullable("lastUpdated"));
    assertTrue(isNullable("sortOrder"));
    assertTrue(isNullable("description"));
    assertTrue(isNullable("formName"));
    assertTrue(isNullable("style"));
    assertTrue(isNullable("optionSet"));
    assertTrue(isNullable("attributeValues"));
  }

  @Test
  @DisplayName("shortName, createdBy, lastUpdatedBy and sharing are not persisted")
  void testUnsupportedPropertiesAreNotMapped() {
    List<String> properties = List.of(persister().getPropertyNames());

    assertFalse(properties.contains("shortName"));
    assertFalse(properties.contains("createdBy"));
    assertFalse(properties.contains("lastUpdatedBy"));
    assertFalse(properties.contains("sharing"));
  }

  @Test
  @DisplayName("the entity is second-level cached with nonstrict-read-write")
  void testCacheStrategy() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(
        AccessType.NONSTRICT_READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("options saved through their option set are linked to it and loaded in sort order")
  void testOptionsAreSavedAndOrderedThroughTheOptionSet() throws ConflictException {
    Option first = new Option("First", "FIRST", 1);
    Option second = new Option("Second", "SECOND", 2);
    Option third = new Option("Third", "THIRD", 3);
    OptionSet optionSet = new OptionSet("Ordered", ValueType.TEXT);
    optionSet.setOptions(new ArrayList<>(List.of(third, first, second)));
    optionService.saveOptionSet(optionSet);
    entityManager.flush();

    List<Long> linkedOptionSetIds =
        jdbcTemplate.queryForList(
            "select optionsetid from optionvalue where optionvalueid in (?, ?, ?)",
            Long.class,
            first.getId(),
            second.getId(),
            third.getId());
    assertEquals(
        List.of(optionSet.getId(), optionSet.getId(), optionSet.getId()), linkedOptionSetIds);

    clearSession();
    entityManagerFactory.getCache().evictAll();
    OptionSet reloaded = optionService.getOptionSet(optionSet.getUid());
    assertEquals(
        List.of("FIRST", "SECOND", "THIRD"),
        reloaded.getOptions().stream().map(Option::getCode).toList());
    assertEquals(optionSet.getUid(), reloaded.getOptions().get(0).getOptionSet().getUid());
  }

  private OptionSet saveOptionSet(String name, Option... options) throws ConflictException {
    OptionSet optionSet = new OptionSet(name, ValueType.TEXT);
    for (Option option : options) {
      optionSet.addOption(option);
    }
    optionService.saveOptionSet(optionSet);
    entityManager.flush();
    return optionSet;
  }

  private static ObjectStyle style(String color, String icon) {
    ObjectStyle style = new ObjectStyle();
    style.setColor(color);
    style.setIcon(icon);
    return style;
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Option.class);
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  /** Reloads the option from the database, bypassing the session and the second-level cache. */
  private Option reload(Option option) {
    clearSession();
    entityManagerFactory.getCache().evict(Option.class);
    return store.get(option.getId());
  }
}
