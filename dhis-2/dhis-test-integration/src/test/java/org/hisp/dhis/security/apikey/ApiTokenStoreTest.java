/** Tests the mapping of {@link ApiToken} to the {@code api_token} table. */
@Transactional
class ApiTokenStoreTest extends PostgresIntegrationTestBase {

  @Autowired private ApiTokenStore apiTokenStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private User owner;

  private User otherUser;

  @BeforeEach
  void setUp() {
    owner = createAndAddUser("tokenowner");
    otherUser = createAndAddUser("tokenother");
    injectSecurityContextUser(owner);
  }

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(
        "apitokenid",
        ((AbstractEntityPersister) persister()).getIdentifierColumnNames()[0].toLowerCase());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back")
  void testColumnsRoundTrip() {
    Date created = new Date(1_600_000_000_000L);
    long expire = System.currentTimeMillis() + TimeUnit.DAYS.toMillis(7);
    TokenWrapper wrapper =
        ApiKeyTokenGenerator.generatePersonalAccessToken(
            List.of(
                IpAllowedList.of("10.0.0.1"),
                MethodAllowedList.of("GET"),
                RefererAllowedList.of("http://referer.example.org")),
            expire,
            "tokenCode1");
    ApiToken token = wrapper.getApiToken();
    token.setUid("apiTokRndT1");
    token.setCreated(created);
    apiTokenStore.save(token);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, created, lastupdated is not null as hasLastUpdated, createdby,"
                + " lastupdatedby, version, type, expire, key,"
                + " attributes -> 0 ->> 'type' as attr0, attributes -> 1 ->> 'type' as attr1,"
                + " attributes -> 2 ->> 'type' as attr2, sharing ->> 'owner' as sharingowner"
                + " from api_token where apitokenid = ?",
            token.getId());
    assertEquals("apiTokRndT1", row.get("uid"));
    assertEquals("tokenCode1", row.get("code"));
    assertEquals(new Timestamp(created.getTime()), row.get("created"));
    assertTrue((Boolean) row.get("hasLastUpdated"));
    assertEquals(owner.getId(), row.get("createdby"));
    assertEquals(owner.getId(), row.get("lastupdatedby"));
    assertEquals(2, row.get("version"));
    assertEquals("PERSONAL_ACCESS_TOKEN_V2", row.get("type"));
    assertEquals(expire, row.get("expire"));
    assertEquals(token.getKey(), row.get("key"));
    assertEquals("IpAllowedList", row.get("attr0"));
    assertEquals("MethodAllowedList", row.get("attr1"));
    assertEquals("RefererAllowedList", row.get("attr2"));
    assertEquals(owner.getUid(), row.get("sharingowner"));

    clearSessionAndSecondLevelCache();

    ApiToken reloaded = entityManager.find(ApiToken.class, token.getId());
    assertEquals("apiTokRndT1", reloaded.getUid());
    assertEquals("tokenCode1", reloaded.getCode());
    assertEquals(created.getTime(), reloaded.getCreated().getTime());
    assertEquals(owner.getUid(), reloaded.getCreatedBy().getUid());
    assertEquals(owner.getUid(), reloaded.getLastUpdatedBy().getUid());
    assertEquals(Integer.valueOf(2), reloaded.getVersion());
    assertSame(ApiTokenType.PERSONAL_ACCESS_TOKEN_V2, reloaded.getType());
    assertEquals(Long.valueOf(expire), reloaded.getExpire());
    assertEquals(token.getKey(), reloaded.getKey());
    assertEquals(owner.getUid(), reloaded.getSharing().getOwner());
    assertEquals(
        List.of(
            IpAllowedList.of("10.0.0.1"),
            MethodAllowedList.of("GET"),
            RefererAllowedList.of("http://referer.example.org")),
        reloaded.getAttributes());
  }

  @Test
  @DisplayName("the key column holds the hash of the plaintext token, never the token itself")
  void testKeyStoresTokenHash() {
    TokenWrapper wrapper = createAndSaveToken();
    String plaintext = new String(wrapper.getPlaintextToken());

    String storedKey =
        jdbcTemplate.queryForObject(
            "select key from api_token where apitokenid = ?",
            String.class,
            wrapper.getApiToken().getId());

    assertEquals(ApiKeyTokenGenerator.hashToken(wrapper.getPlaintextToken()), storedKey);
    assertNotEquals(plaintext, storedKey);
    assertFalse(storedKey.contains(plaintext));
  }

  @Test
  @DisplayName("a token is found by its hashed key, and by key and owner only for its owner")
  void testGetByKey() {
    ApiToken token = createAndSaveToken().getApiToken();
    clearSessionAndSecondLevelCache();

    assertEquals(token.getUid(), apiTokenStore.getByKey(token.getKey()).getUid());
    assertEquals(token.getUid(), apiTokenStore.getByKey(token.getKey(), owner).getUid());
    assertNull(apiTokenStore.getByKey(token.getKey(), otherUser));
    assertNull(apiTokenStore.getByKey("not-a-stored-key"));
  }

  @Test
  @DisplayName("getAllOwning returns only the tokens created by the given user")
  void testGetAllOwning() {
    ApiToken ownersToken = createAndSaveToken().getApiToken();
    injectSecurityContextUser(otherUser);
    ApiToken othersToken = createAndSaveToken().getApiToken();
    clearSessionAndSecondLevelCache();

    assertEquals(
        List.of(ownersToken.getUid()),
        apiTokenStore.getAllOwning(owner).stream().map(ApiToken::getUid).toList());
    assertEquals(
        List.of(othersToken.getUid()),
        apiTokenStore.getAllOwning(otherUser).stream().map(ApiToken::getUid).toList());
  }

  @Test
  @DisplayName("createdBy and lastUpdatedBy are mapped to the createdby and lastupdatedby columns")
  void testUserColumns() {
    AbstractEntityPersister persister = (AbstractEntityPersister) persister();

    assertEquals(List.of("createdby"), List.of(persister.getPropertyColumnNames("createdBy")));
    assertEquals(
        List.of("lastupdatedby"), List.of(persister.getPropertyColumnNames("lastUpdatedBy")));
  }

  @Test
  @DisplayName(
      "uid, created, lastUpdated, key, version, type and expire are mapped not-null, the others"
          + " nullable")
  void testNullability() {
    EntityPersister persister = persister();
    boolean[] nullable = persister.getPropertyNullability();

    for (String property :
        List.of("uid", "created", "lastUpdated", "key", "version", "type", "expire")) {
      assertFalse(nullable[propertyIndex(persister, property)], property);
    }
    for (String property : List.of("code", "createdBy", "lastUpdatedBy", "attributes", "sharing")) {
      assertTrue(nullable[propertyIndex(persister, property)], property);
    }
  }

  @Test
  @DisplayName("created is not updatable")
  void testCreatedIsNotUpdatable() {
    EntityPersister persister = persister();

    assertFalse(persister.getPropertyUpdateability()[propertyIndex(persister, "created")]);
  }

  @Test
  @DisplayName("type is bound as a named enum, attributes and sharing as their JSONB types")
  void testPropertyTypes() {
    EntityPersister persister = persister();

    CustomType type = assertInstanceOf(CustomType.class, persister.getPropertyType("type"));
    EnumType<?> enumType = assertInstanceOf(EnumType.class, type.getUserType());
    assertEquals(ApiTokenType.class, enumType.returnedClass());
    assertFalse(enumType.isOrdinal());

    CustomType attributes =
        assertInstanceOf(CustomType.class, persister.getPropertyType("attributes"));
    assertInstanceOf(ApiKeyAttributeJsonBinaryType.class, attributes.getUserType());

    CustomType sharing = assertInstanceOf(CustomType.class, persister.getPropertyType("sharing"));
    assertInstanceOf(SharingJsonBinaryType.class, sharing.getUserType());
  }

  @Test
  @DisplayName("createdBy and lastUpdatedBy are loaded lazily")
  void testUsersAreLazy() {
    for (String property : List.of("createdBy", "lastUpdatedBy")) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
      assertFalse(type.isEager(null), property);
    }
  }

  @Test
  @DisplayName("the entity is second-level cached read-write")
  void testEntityCacheIsReadWrite() {
    assertEquals(AccessType.READ_WRITE, persister().getCacheAccessStrategy().getAccessType());
  }

  private TokenWrapper createAndSaveToken() {
    TokenWrapper wrapper =
        ApiKeyTokenGenerator.generatePersonalAccessToken(
            null, System.currentTimeMillis() + TimeUnit.DAYS.toMillis(30), null);
    apiTokenStore.save(wrapper.getApiToken());
    entityManager.flush();
    return wrapper;
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ApiToken.class);
  }

  private static int propertyIndex(EntityPersister persister, String property) {
    return persister.getEntityMetamodel().getPropertyIndex(property);
  }
}
