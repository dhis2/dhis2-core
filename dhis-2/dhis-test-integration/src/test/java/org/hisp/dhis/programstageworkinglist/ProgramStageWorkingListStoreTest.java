@Transactional
class ProgramStageWorkingListStoreTest extends PostgresIntegrationTestBase {
  @Autowired private ProgramStageWorkingListStore store;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private Program program;

  private ProgramStage programStage;

  @BeforeEach
  void setUp() {
    program = createProgram('A');
    manager.save(program);
    programStage = createProgramStage('A', program);
    manager.save(programStage);
  }

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void shouldWriteAndReadBackEveryMappedColumn() {
    User admin = getAdminUser();
    ProgramStageWorkingList workingList = createWorkingList("Working list A");
    workingList.setCode("PSWL_A");
    workingList.setDescription("Description A");
    workingList.setLastUpdatedBy(admin);
    workingList.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Liste A")));
    workingList.getSharing().setPublicAccess("rw------");
    store.save(workingList, false);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, description, created, lastupdated, lastupdatedby, userid,"
                + " programid, programstageid, translations::text as translations,"
                + " sharing->>'public' as publicaccess, sharing->>'owner' as owner,"
                + " programstagequerycriteria->>'order' as criteriaorder"
                + " from programstageworkinglist where programstageworkinglistid = ?",
            workingList.getId());
    assertEquals(workingList.getUid(), row.get("uid"));
    assertEquals("PSWL_A", row.get("code"));
    assertEquals("Working list A", row.get("name"));
    assertEquals("Description A", row.get("description"));
    assertEquals(workingList.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(workingList.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(admin.getId(), ((Number) row.get("lastupdatedby")).longValue());
    assertEquals(admin.getId(), ((Number) row.get("userid")).longValue());
    assertEquals(program.getId(), ((Number) row.get("programid")).longValue());
    assertEquals(programStage.getId(), ((Number) row.get("programstageid")).longValue());
    assertTrue(((String) row.get("translations")).contains("\"Liste A\""));
    assertEquals("rw------", row.get("publicaccess"));
    assertEquals(admin.getUid(), row.get("owner"));
    assertEquals("createdAt:desc", row.get("criteriaorder"));

    ProgramStageWorkingList reloaded = reload(workingList);
    assertEquals(workingList.getUid(), reloaded.getUid());
    assertEquals("PSWL_A", reloaded.getCode());
    assertEquals("Working list A", reloaded.getName());
    assertEquals("Description A", reloaded.getDescription());
    assertEquals(workingList.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(workingList.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(admin.getUid(), reloaded.getLastUpdatedBy().getUid());
    assertEquals(admin.getUid(), reloaded.getCreatedBy().getUid());
    assertEquals(program.getUid(), reloaded.getProgram().getUid());
    assertEquals(programStage.getUid(), reloaded.getProgramStage().getUid());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Liste A")), reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals("createdAt:desc", reloaded.getProgramStageQueryCriteria().getOrder());
  }

  @Test
  @DisplayName("the whole program stage query criteria is stored and read back unchanged")
  void shouldStoreAndReadBackWholeProgramStageQueryCriteria() throws JsonProcessingException {
    ProgramStageWorkingList workingList = createWorkingList("Working list B");
    ProgramStageQueryCriteria criteria = createFullCriteria();
    workingList.setProgramStageQueryCriteria(criteria);
    ProgramStageWorkingList saved = save(workingList);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select programstagequerycriteria->'dataFilters'->0->>'dataItem' as dataitem,"
                + " programstagequerycriteria->'attributeValueFilters'->0->>'attribute' as attr,"
                + " programstagequerycriteria->'eventScheduledAt'->>'startBuffer' as startbuffer,"
                + " programstagequerycriteria->>'followUp' as followup"
                + " from programstageworkinglist where programstageworkinglistid = ?",
            saved.getId());
    assertEquals("DATAEL00001", row.get("dataitem"));
    assertEquals("TeaUid00001", row.get("attr"));
    assertEquals("-5", row.get("startbuffer"));
    assertEquals("true", row.get("followup"));

    ProgramStageQueryCriteria reloaded = reload(saved).getProgramStageQueryCriteria();

    ObjectMapper mapper = new ObjectMapper();
    assertEquals(mapper.writeValueAsString(criteria), mapper.writeValueAsString(reloaded));
    assertEquals(EventStatus.ACTIVE, reloaded.getEventStatus());
    assertEquals(DatePeriodType.ABSOLUTE, reloaded.getEventOccurredAt().getType());
    assertEquals(new Date(1_700_000_000_000L), reloaded.getEventOccurredAt().getStartDate());
    assertEquals(Set.of("a"), reloaded.getDataFilters().get(0).getIn());
    assertTrue(reloaded.getAttributeValueFilters().get(0).getNull());
    assertEquals(List.of("colA", "colB"), reloaded.getDisplayColumnOrder());
  }

  @Test
  @DisplayName("description is bound as text")
  void shouldBindDescriptionAsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
  }

  @Test
  @DisplayName("program and programStage are eager many-to-ones fetched by a separate select")
  void shouldFetchProgramAndProgramStageEagerlyBySelect() {
    assertEagerBySelect("program");
    assertEagerBySelect("programStage");
  }

  @Test
  @DisplayName("name, program and programStage are mapped not-null")
  void shouldMapNameProgramAndProgramStageNotNull() {
    assertNotNullable("name");
    assertNotNullable("program");
    assertNotNullable("programStage");
    assertNullable("code");
    assertNullable("description");
    assertNullable("programStageQueryCriteria");
  }

  @Test
  @DisplayName("changing created on a stored working list does not update its created column")
  void shouldKeepCreatedWhenStoredWorkingListChanges() {
    ProgramStageWorkingList saved = save(createWorkingList("Working list E"));
    Date created = queryCreated(saved);

    saved.setCreated(new Date(created.getTime() - 86_400_000L));
    saved.setName("Working list E renamed");
    entityManager.flush();

    assertEquals("Working list E renamed", reload(saved).getName());
    assertEquals(created, queryCreated(saved));
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("a null translations column is read as no translations")
  void shouldReadNullTranslationsColumnAsEmpty() {
    ProgramStageWorkingList saved = save(createWorkingList("Working list C"));
    jdbcTemplate.update(
        "update programstageworkinglist set translations = null"
            + " where programstageworkinglistid = ?",
        saved.getId());

    ProgramStageWorkingList reloaded = reload(saved);

    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals("Working list C", reloaded.getDisplayName());
  }

  @Test
  @DisplayName("a null sharing column is read as empty sharing")
  void shouldReadNullSharingColumnAsEmptySharing() {
    ProgramStageWorkingList saved = save(createWorkingList("Working list D"));
    jdbcTemplate.update(
        "update programstageworkinglist set sharing = null where programstageworkinglistid = ?",
        saved.getId());

    ProgramStageWorkingList reloaded = reload(saved);

    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
  }

  private ProgramStageWorkingList createWorkingList(String name) {
    ProgramStageWorkingList workingList = new ProgramStageWorkingList();
    workingList.setAutoFields();
    workingList.setName(name);
    workingList.setProgram(program);
    workingList.setProgramStage(programStage);
    workingList.setProgramStageQueryCriteria(
        ProgramStageQueryCriteria.builder().order("createdAt:desc").build());
    return workingList;
  }

  private static ProgramStageQueryCriteria createFullCriteria() {
    EventDataFilter dataFilter = new EventDataFilter();
    dataFilter.setDataItem("DATAEL00001");
    dataFilter.setGe("1");
    dataFilter.setLe("10");
    dataFilter.setIn(Set.of("a"));
    dataFilter.setLike("x");
    dataFilter.setNull(false);
    dataFilter.setDateFilter(relative(RelativePeriodEnum.TODAY));

    AttributeValueFilter attributeFilter = new AttributeValueFilter();
    attributeFilter.setAttribute("TeaUid00001");
    attributeFilter.setEq("v");
    attributeFilter.setSw("s");
    attributeFilter.setEw("e");
    attributeFilter.setNull(true);
    attributeFilter.setDateFilter(absolute());

    DateFilterPeriod buffers = new DateFilterPeriod();
    buffers.setType(DatePeriodType.RELATIVE);
    buffers.setStartBuffer(-5);
    buffers.setEndBuffer(5);

    return ProgramStageQueryCriteria.builder()
        .eventStatus(EventStatus.ACTIVE)
        .eventCreatedAt(relative(RelativePeriodEnum.LAST_WEEK))
        .eventOccurredAt(absolute())
        .eventScheduledAt(buffers)
        .enrollmentStatus(EnrollmentStatus.COMPLETED)
        .enrolledAt(relative(RelativePeriodEnum.THIS_YEAR))
        .enrollmentOccurredAt(absolute())
        .order("createdAt:desc,occurredAt:asc")
        .displayColumnOrder(List.of("colA", "colB"))
        .orgUnit("OrgUnit0001")
        .ouMode(OrganisationUnitSelectionMode.SELECTED)
        .assignedUserMode(AssignedUserSelectionMode.PROVIDED)
        .assignedUsers(Set.of("UserUid0001"))
        .dataFilters(List.of(dataFilter))
        .attributeValueFilters(List.of(attributeFilter))
        .followUp(true)
        .build();
  }

  private static DateFilterPeriod relative(RelativePeriodEnum period) {
    DateFilterPeriod filter = new DateFilterPeriod();
    filter.setType(DatePeriodType.RELATIVE);
    filter.setPeriod(period);
    return filter;
  }

  private static DateFilterPeriod absolute() {
    DateFilterPeriod filter = new DateFilterPeriod();
    filter.setType(DatePeriodType.ABSOLUTE);
    filter.setStartDate(new Date(1_700_000_000_000L));
    filter.setEndDate(new Date(1_710_000_000_000L));
    return filter;
  }

  private void assertEagerBySelect(String property) {
    AbstractEntityPersister persister = (AbstractEntityPersister) persister();
    int index = persister.getEntityMetamodel().getPropertyIndex(property);

    assertTrue(
        assertInstanceOf(ManyToOneType.class, persister.getPropertyType(property)).isEager(null));
    assertEquals(org.hibernate.FetchMode.SELECT, persister.getFetchMode(index));
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ProgramStageWorkingList.class);
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private ProgramStageWorkingList save(ProgramStageWorkingList workingList) {
    store.save(workingList);
    entityManager.flush();
    return workingList;
  }

  private Date queryCreated(ProgramStageWorkingList workingList) {
    return jdbcTemplate.queryForObject(
        "select created from programstageworkinglist where programstageworkinglistid = ?",
        Date.class,
        workingList.getId());
  }

  /** Reloads the working list from the database, bypassing the session and the L2 cache. */
  private ProgramStageWorkingList reload(ProgramStageWorkingList workingList) {
    clearSession();
    entityManagerFactory.getCache().evict(ProgramStageWorkingList.class);
    return store.get(workingList.getId());
  }
}
