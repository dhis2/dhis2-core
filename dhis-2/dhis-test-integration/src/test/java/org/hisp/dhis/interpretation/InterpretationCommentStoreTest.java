package org.hisp.dhis.interpretation;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.sql.Timestamp;
import java.util.Date;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.type.CustomType;
import org.hibernate.type.ManyToOneType;
import org.hibernate.type.TextType;
import org.hisp.dhis.hibernate.jsonb.type.JsonListBinaryType;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.hisp.dhis.user.User;
import org.hisp.dhis.visualization.Visualization;
import org.hisp.dhis.visualization.VisualizationService;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the mapping of {@link InterpretationComment} and its ownership by an interpretation. */
@Transactional
class InterpretationCommentStoreTest extends PostgresIntegrationTestBase {

  @Autowired private InterpretationStore interpretationStore;

  @Autowired private VisualizationService visualizationService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private User userA;

  private User userB;

  private Visualization visualization;

  @BeforeEach
  void setUp() {
    userA = createAndAddUser("commentusera");
    userB = createAndAddUser("commentuserb");
    visualization = createVisualization('A');
    visualizationService.save(visualization);
  }

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName(
      "uid, created, lastUpdated, text, mentions and createdBy are written to their columns and"
          + " read back")
  void testColumnsRoundTrip() {
    Date created = new Date(1_600_000_000_000L);
    Date lastUpdated = new Date(1_700_000_000_000L);
    InterpretationComment comment = comment("cmtRoundTr1", "Round trip text", userA);
    comment.setCreated(created);
    comment.setLastUpdated(lastUpdated);
    comment.setMentionsFromUsers(Set.of(userB));
    saveInterpretation(comment);

    assertEquals(
        Map.of(
            "uid",
            "cmtRoundTr1",
            "created",
            new Timestamp(created.getTime()),
            "lastupdated",
            new Timestamp(lastUpdated.getTime()),
            "commenttext",
            "Round trip text",
            "userid",
            userA.getId(),
            "username",
            userB.getUsername()),
        jdbcTemplate.queryForMap(
            "select uid, created, lastupdated, commenttext, userid,"
                + " mentions -> 0 ->> 'username' as username"
                + " from interpretationcomment where interpretationcommentid = ?",
            comment.getId()));

    clearSessionAndSecondLevelCache();

    InterpretationComment reloaded =
        entityManager.find(InterpretationComment.class, comment.getId());
    assertEquals("cmtRoundTr1", reloaded.getUid());
    assertEquals(created.getTime(), reloaded.getCreated().getTime());
    assertEquals(lastUpdated.getTime(), reloaded.getLastUpdated().getTime());
    assertEquals("Round trip text", reloaded.getText());
    assertEquals(userA.getUid(), reloaded.getCreatedBy().getUid());
    assertEquals(1, reloaded.getMentions().size());
    assertEquals(userB.getUsername(), reloaded.getMentions().get(0).getUsername());
  }

  @Test
  @DisplayName("createdBy, created and lastUpdated are mapped not-null, uid, text and mentions not")
  void testNullability() {
    EntityPersister persister = persister();
    boolean[] nullable = persister.getPropertyNullability();

    assertFalse(nullable[propertyIndex(persister, "createdBy")]);
    assertFalse(nullable[propertyIndex(persister, "created")]);
    assertFalse(nullable[propertyIndex(persister, "lastUpdated")]);
    assertTrue(nullable[propertyIndex(persister, "uid")]);
    assertTrue(nullable[propertyIndex(persister, "text")]);
    assertTrue(nullable[propertyIndex(persister, "mentions")]);
  }

  @Test
  @DisplayName("text is bound as text and mentions as a JSON list of Mention")
  void testPropertyTypes() {
    EntityPersister persister = persister();

    assertInstanceOf(TextType.class, persister.getPropertyType("text"));
    CustomType mentions = assertInstanceOf(CustomType.class, persister.getPropertyType("mentions"));
    JsonListBinaryType userType =
        assertInstanceOf(JsonListBinaryType.class, mentions.getUserType());
    assertEquals(Mention.class, userType.returnedClass());
  }

  @Test
  @DisplayName("createdBy is loaded lazily")
  void testCreatedByIsLazy() {
    ManyToOneType type =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("createdBy"));

    assertFalse(type.isEager(null));
  }

  @Test
  @DisplayName("the comment entity is not second-level cached")
  void testEntityIsNotCached() {
    EntityPersister persister = persister();

    assertFalse(persister.canReadFromCache());
    assertNull(persister.getCacheAccessStrategy());
  }

  @Test
  @DisplayName(
      "an interpretation saves its comments by cascade in list order and deletes a removed comment"
          + " with its join row")
  void testInterpretationOwnsCommentsInOrder() {
    InterpretationComment first = comment("cmtOrderAA1", "First", userA);
    InterpretationComment second = comment("cmtOrderBB1", "Second", userB);
    long interpretationId = saveInterpretation(first, second);

    assertEquals(List.of(first.getId(), second.getId()), joinRows(interpretationId));

    clearSessionAndSecondLevelCache();

    Interpretation loaded = interpretationStore.get(interpretationId);
    assertEquals(
        List.of("cmtOrderAA1", "cmtOrderBB1"),
        loaded.getComments().stream().map(InterpretationComment::getUid).toList());
    loaded.getComments().remove(0);
    interpretationStore.update(loaded);
    clearSessionAndSecondLevelCache();

    assertEquals(List.of(second.getId()), joinRows(interpretationId));
    assertEquals(0, countCommentRows(first.getId()));
    assertEquals(1, countCommentRows(second.getId()));
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(InterpretationComment.class);
  }

  private static int propertyIndex(EntityPersister persister, String property) {
    return persister.getEntityMetamodel().getPropertyIndex(property);
  }

  private static InterpretationComment comment(String uid, String text, User createdBy) {
    InterpretationComment comment = new InterpretationComment(text);
    comment.setUid(uid);
    comment.setLastUpdated(new Date());
    comment.setCreatedBy(createdBy);
    return comment;
  }

  private long saveInterpretation(InterpretationComment... comments) {
    Interpretation interpretation = new Interpretation(visualization, null, "Interpretation");
    for (InterpretationComment comment : comments) {
      interpretation.addComment(comment);
    }
    interpretationStore.save(interpretation);
    entityManager.flush();
    return interpretation.getId();
  }

  /** Comment ids of the interpretation's join rows, in sort order. */
  private List<Long> joinRows(long interpretationId) {
    return jdbcTemplate.queryForList(
        "select interpretationcommentid from interpretation_comments"
            + " where interpretationid = ? order by sort_order",
        Long.class,
        interpretationId);
  }

  private int countCommentRows(long commentId) {
    return jdbcTemplate.queryForObject(
        "select count(*) from interpretationcomment where interpretationcommentid = ?",
        Integer.class,
        commentId);
  }
}
