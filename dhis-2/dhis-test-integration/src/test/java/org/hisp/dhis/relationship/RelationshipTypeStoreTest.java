@Transactional
class RelationshipTypeStoreTest extends PostgresIntegrationTestBase {
  @Autowired private RelationshipTypeStore store;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every property declared by RelationshipType is written to its column")
  void shouldWriteEveryRelationshipTypeColumn() {
    RelationshipType type = saveFullRelationshipType();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, description, bidirectional, referral, fromtoname, tofromname,"
                + " from_relationshipconstraintid, to_relationshipconstraintid,"
                + " translations::text as translations, sharing->>'public' as publicaccess,"
                + " attributevalues->'AttrUid0001'->>'value' as attributevalue"
                + " from relationshiptype where relationshiptypeid = ?",
            type.getId());
    assertEquals("RT_A", row.get("code"));
    assertEquals("Relationship type A", row.get("name"));
    assertEquals("Description A", row.get("description"));
    assertEquals(Boolean.TRUE, row.get("bidirectional"));
    assertEquals(Boolean.TRUE, row.get("referral"));
    assertEquals("Parent of", row.get("fromtoname"));
    assertEquals("Child of", row.get("tofromname"));
    assertEquals(type.getFromConstraint().getId(), row.get("from_relationshipconstraintid"));
    assertEquals(type.getToConstraint().getId(), row.get("to_relationshipconstraintid"));
    assertTrue(((String) row.get("translations")).contains("\"Parent de\""));
    assertEquals("rw------", row.get("publicaccess"));
    assertEquals("attribute value", row.get("attributevalue"));
  }

  @Test
  @DisplayName("every property declared by RelationshipType is read back from its column")
  void shouldReadBackEveryRelationshipTypeProperty() {
    RelationshipType type = saveFullRelationshipType();

    RelationshipType reloaded = reload(type);

    assertEquals("RT_A", reloaded.getCode());
    assertEquals("Relationship type A", reloaded.getName());
    assertEquals("Description A", reloaded.getDescription());
    assertTrue(reloaded.isBidirectional());
    assertTrue(reloaded.isReferral());
    assertEquals("Parent of", reloaded.getFromToName());
    assertEquals("Child of", reloaded.getToFromName());
    assertEquals(
        RelationshipEntity.TRACKED_ENTITY_INSTANCE,
        reloaded.getFromConstraint().getRelationshipEntity());
    assertEquals(
        type.getFromConstraint().getTrackedEntityType().getUid(),
        reloaded.getFromConstraint().getTrackedEntityType().getUid());
    assertEquals(
        RelationshipEntity.PROGRAM_STAGE_INSTANCE,
        reloaded.getToConstraint().getRelationshipEntity());
    assertEquals(
        Set.of(
            new Translation(new Locale("fr"), "RELATIONSHIP_FROM_TO_NAME", "Parent de"),
            new Translation(new Locale("fr"), "RELATIONSHIP_TO_FROM_NAME", "Enfant de")),
        reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(getAdminUser().getUid(), reloaded.getSharing().getOwner());
    assertEquals("attribute value", reloaded.getAttributeValues().get("AttrUid0001"));
  }

  @Test
  @DisplayName("saving a relationship type saves both constraints and deleting it deletes them")
  void shouldCascadeSaveAndDeleteToConstraints() {
    RelationshipType type = save(createRelationshipType('B'));
    int fromId = type.getFromConstraint().getId();
    int toId = type.getToConstraint().getId();
    assertEquals(2, countConstraints(fromId, toId));

    store.delete(type);
    entityManager.flush();

    assertEquals(0, countConstraints(fromId, toId));
  }

  @Test
  @DisplayName("replacing a constraint deletes the previous constraint row")
  void shouldDeleteReplacedConstraint() {
    RelationshipType type = save(createRelationshipType('C'));
    int oldFromId = type.getFromConstraint().getId();
    int toId = type.getToConstraint().getId();
    RelationshipConstraint newFrom = new RelationshipConstraint();
    newFrom.setRelationshipEntity(RelationshipEntity.PROGRAM_INSTANCE);

    type.setFromConstraint(newFrom);
    store.update(type);
    entityManager.flush();

    assertEquals(0, countConstraints(oldFromId));
    assertEquals(1, countConstraints(toId));
    RelationshipType reloaded = reload(type);
    assertNotEquals(oldFromId, reloaded.getFromConstraint().getId());
    assertEquals(
        RelationshipEntity.PROGRAM_INSTANCE, reloaded.getFromConstraint().getRelationshipEntity());
  }

  @Test
  @DisplayName("the constraints are lazy one-to-one many-to-one references with orphan delete")
  void shouldMapConstraintsAsLazyOneToOneReferencesWithOrphanDelete() {
    EntityPersister persister = persister();
    for (String property : new String[] {"fromConstraint", "toConstraint"}) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister.getPropertyType(property));
      int index = persister.getEntityMetamodel().getPropertyIndex(property);

      assertFalse(type.isEager(null), property + " is eager");
      assertTrue(type.isLogicalOneToOne(), property + " is not a one-to-one reference");
      assertTrue(
          persister.getPropertyCascadeStyles()[index].hasOrphanDelete(),
          property + " has no orphan delete");
    }
  }

  @Test
  @DisplayName("sharing and attribute values are bound to their typedefs")
  void shouldBindJsonbPropertiesToTheirTypedefs() {
    assertInstanceOf(SharingJsonBinaryType.class, customType("sharing").getUserType());
    assertInstanceOf(
        JsonAttributeValuesBinaryType.class, customType("attributeValues").getUserType());
  }

  @Test
  @DisplayName("only name, fromToName, bidirectional and referral are mapped not-null")
  void shouldMapOnlyNameFromToNameAndFlagsNotNull() {
    assertNotNullable("name");
    assertNotNullable("fromToName");
    assertNotNullable("bidirectional");
    assertNotNullable("referral");
    assertNullable("code");
    assertNullable("description");
    assertNullable("toFromName");
    assertNullable("fromConstraint");
    assertNullable("toConstraint");
    assertNullable("translations");
    assertNullable("sharing");
    assertNullable("attributeValues");
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("a relationship type is found by its code")
  void shouldGetRelationshipTypeByCode() {
    RelationshipType type = createRelationshipType('D');
    type.setCode("RT_D");
    save(type);
    clearSession();

    assertEquals(type.getUid(), store.getByCodeNoAcl("RT_D").getUid());
  }

  @Test
  @DisplayName("an uninitialized proxy equals an instance with the same uid, code and name")
  void shouldEqualProxyWithSameIdentity() {
    RelationshipType saved = save(createRelationshipType('E'));
    clearSession();
    entityManagerFactory.getCache().evict(RelationshipType.class);
    RelationshipType copy = new RelationshipType();
    copy.setUid(saved.getUid());
    copy.setCode(saved.getCode());
    copy.setName(saved.getName());

    RelationshipType proxy = entityManager.getReference(RelationshipType.class, saved.getId());

    assertInstanceOf(HibernateProxy.class, proxy);
    assertEquals(copy, proxy);
    assertEquals(proxy, copy);
    assertEquals(copy.hashCode(), proxy.hashCode());
  }

  @Test
  @DisplayName("null translations, sharing and attribute values columns are read as empty")
  void shouldReadNullJsonbColumnsAsEmpty() {
    RelationshipType saved = save(createRelationshipType('F'));
    jdbcTemplate.update(
        "update relationshiptype set translations = null, sharing = null, attributevalues = null"
            + " where relationshiptypeid = ?",
        saved.getId());

    RelationshipType reloaded = reload(saved);

    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals(reloaded.getFromToName(), reloaded.getDisplayFromToName());
    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
    assertTrue(reloaded.getAttributeValues().isEmpty());
  }

  private RelationshipType saveFullRelationshipType() {
    User admin = getAdminUser();
    TrackedEntityType trackedEntityType = createTrackedEntityType('A');
    manager.save(trackedEntityType);
    RelationshipConstraint from = new RelationshipConstraint();
    from.setRelationshipEntity(RelationshipEntity.TRACKED_ENTITY_INSTANCE);
    from.setTrackedEntityType(trackedEntityType);
    RelationshipConstraint to = new RelationshipConstraint();
    to.setRelationshipEntity(RelationshipEntity.PROGRAM_STAGE_INSTANCE);

    RelationshipType type = new RelationshipType();
    type.setAutoFields();
    type.setCode("RT_A");
    type.setName("Relationship type A");
    type.setDescription("Description A");
    type.setBidirectional(true);
    type.setReferral(true);
    type.setFromToName("Parent of");
    type.setToFromName("Child of");
    type.setFromConstraint(from);
    type.setToConstraint(to);
    type.setTranslations(
        Set.of(
            new Translation(new Locale("fr"), "RELATIONSHIP_FROM_TO_NAME", "Parent de"),
            new Translation(new Locale("fr"), "RELATIONSHIP_TO_FROM_NAME", "Enfant de")));
    type.getSharing().setPublicAccess("rw------");
    type.getSharing().setOwner(admin.getUid());
    type.addAttributeValue("AttrUid0001", "attribute value");
    store.save(type, false);
    entityManager.flush();
    return type;
  }

  private int countConstraints(Integer... ids) {
    return jdbcTemplate.queryForObject(
        "select count(*) from relationshipconstraint where relationshipconstraintid = any(?)",
        Integer.class,
        (Object) ids);
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(RelationshipType.class);
  }

  private CustomType customType(String property) {
    return assertInstanceOf(CustomType.class, persister().getPropertyType(property));
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private RelationshipType save(RelationshipType type) {
    store.save(type);
    entityManager.flush();
    return type;
  }

  /** Reloads the relationship type from the database, bypassing the session and the L2 cache. */
  private RelationshipType reload(RelationshipType type) {
    clearSession();
    entityManagerFactory.getCache().evict(RelationshipType.class);
    entityManagerFactory.getCache().evict(RelationshipConstraint.class);
    return store.get(type.getId());
  }
}
