package org.hisp.dhis.notification.logging;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.sql.Timestamp;
import java.util.Date;
import java.util.Map;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.proxy.HibernateProxy;
import org.hibernate.type.CustomType;
import org.hibernate.type.EnumType;
import org.hibernate.type.TextType;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/**
 * Pins the column mapping, types, nullability and caching of {@link ExternalNotificationLogEntry}
 * through the persister and JDBC, plus the store's key and template uid lookups.
 */
@Transactional
class ExternalNotificationLogEntryStoreTest extends PostgresIntegrationTestBase {

  @Autowired private NotificationLoggingStore notificationLoggingStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back")
  void testColumnsRoundTrip() {
    Date created = new Date(1_500_000_000_000L);
    Date lastSentAt = new Date(1_600_000_000_000L);
    ExternalNotificationLogEntry entry = entry("extNotRnd01", "roundTripKey", "tmplRound01");
    entry.setCreated(created);
    entry.setLastSentAt(lastSentAt);
    entry.setRetries(3);
    entry.setAllowMultiple(true);
    entry.setNotificationTriggeredBy(NotificationTriggerEvent.PROGRAM_STAGE);
    notificationLoggingStore.save(entry);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, created, lastupdated, lastsentat, retries, key, templateuid,"
                + " allowmultiple, triggerby from externalnotificationlogentry"
                + " where externalnotificationlogentryid = ?",
            entry.getId());
    assertEquals("extNotRnd01", row.get("uid"));
    assertEquals(new Timestamp(created.getTime()), row.get("created"));
    assertEquals(new Timestamp(entry.getLastUpdated().getTime()), row.get("lastupdated"));
    assertEquals(new Timestamp(lastSentAt.getTime()), row.get("lastsentat"));
    assertEquals(3, row.get("retries"));
    assertEquals("roundTripKey", row.get("key"));
    assertEquals("tmplRound01", row.get("templateuid"));
    assertEquals(true, row.get("allowmultiple"));
    assertEquals("PROGRAM_STAGE", row.get("triggerby"));

    clearSessionAndSecondLevelCache();

    ExternalNotificationLogEntry reloaded = notificationLoggingStore.get(entry.getId());
    assertEquals("extNotRnd01", reloaded.getUid());
    assertEquals(created.getTime(), reloaded.getCreated().getTime());
    assertEquals(entry.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(lastSentAt.getTime(), reloaded.getLastSentAt().getTime());
    assertEquals(3, reloaded.getRetries());
    assertEquals("roundTripKey", reloaded.getKey());
    assertEquals("tmplRound01", reloaded.getNotificationTemplateUid());
    assertTrue(reloaded.isAllowMultiple());
    assertEquals(NotificationTriggerEvent.PROGRAM_STAGE, reloaded.getNotificationTriggeredBy());
  }

  @Test
  @DisplayName("the trigger event is stored as the name of the enum constant")
  void testTriggerEventIsStoredByName() {
    CustomType type =
        assertInstanceOf(CustomType.class, persister().getPropertyType("notificationTriggeredBy"));
    EnumType<?> enumType = assertInstanceOf(EnumType.class, type.getUserType());

    assertFalse(enumType.isOrdinal());
    assertEquals(NotificationTriggerEvent.class, enumType.returnedClass());
  }

  @Test
  @DisplayName("key and template uid are bound as text")
  void testKeyAndTemplateUidAreText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("key"));
    assertInstanceOf(TextType.class, persister().getPropertyType("notificationTemplateUid"));
  }

  @Test
  @DisplayName("created, last updated, key and template uid are mapped not-null, the rest not")
  void testNullability() {
    assertFalse(isNullable("created"));
    assertFalse(isNullable("lastUpdated"));
    assertFalse(isNullable("key"));
    assertFalse(isNullable("notificationTemplateUid"));
    assertTrue(isNullable("uid"));
    assertTrue(isNullable("lastSentAt"));
    assertTrue(isNullable("retries"));
    assertTrue(isNullable("allowMultiple"));
    assertTrue(isNullable("notificationTriggeredBy"));
  }

  @Test
  @DisplayName("the entity is not second-level cached")
  void testNotCached() {
    assertFalse(persister().canReadFromCache());
    assertNull(persister().getCacheAccessStrategy());
  }

  @Test
  @DisplayName("get by key and get by template uid find the entry by those columns")
  void testGetByKeyAndByTemplateUid() {
    notificationLoggingStore.save(entry("extNotKey01", "keyOne", "tmplKey0001"));
    notificationLoggingStore.save(entry("extNotKey02", "keyTwo", "tmplKey0002"));
    clearSessionAndSecondLevelCache();

    assertEquals("extNotKey02", notificationLoggingStore.getByKey("keyTwo").getUid());
    assertEquals("extNotKey01", notificationLoggingStore.getByTemplateUid("tmplKey0001").getUid());
    assertNull(notificationLoggingStore.getByKey("unknownKey"));
  }

  @Test
  @DisplayName(
      "a lazy proxy and an entry with the same uid are equal both ways with equal hash codes")
  void testProxyEqualsEntryWithSameUid() {
    ExternalNotificationLogEntry saved = entry("extNotPrx01", "proxyKey", "tmplProxy01");
    notificationLoggingStore.save(saved);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    ExternalNotificationLogEntry proxy =
        entityManager.getReference(ExternalNotificationLogEntry.class, saved.getId());
    ExternalNotificationLogEntry other = entry("extNotPrx01", "otherKey", "tmplOther01");

    assertInstanceOf(HibernateProxy.class, proxy);
    assertEquals(proxy, other);
    assertEquals(other, proxy);
    assertEquals(other.hashCode(), proxy.hashCode());
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(ExternalNotificationLogEntry.class);
  }

  private static ExternalNotificationLogEntry entry(
      String uid, String key, String notificationTemplateUid) {
    ExternalNotificationLogEntry entry = new ExternalNotificationLogEntry();
    entry.setUid(uid);
    entry.setKey(key);
    entry.setNotificationTemplateUid(notificationTemplateUid);
    entry.setNotificationTriggeredBy(NotificationTriggerEvent.PROGRAM);
    return entry;
  }
}
