import org.springframework.transaction.annotation.Transactional;

/** Tests the persistence mapping of {@link IndicatorType} to the indicatortype table. */
@Transactional
class IndicatorTypeStoreTest extends PostgresIntegrationTestBase {

  @Autowired
  @Qualifier("org.hisp.dhis.indicator.IndicatorTypeStore")
  private IdentifiableObjectStore<IndicatorType> store;

  @Autowired private IndicatorStore indicatorStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() {
    User admin = getAdminUser();
    IndicatorType type = new IndicatorType("Per thousand", 1000, true);
    type.setCode("CODE_PER_THOUSAND");
    type.setLastUpdatedBy(admin);
    type.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Pour mille")));
    IndicatorType saved = save(type);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, indicatorfactor, indicatornumber, created, lastupdated,"
                + " lastupdatedby, translations::text as translations"
                + " from indicatortype where indicatortypeid = ?",
            saved.getId());
    assertEquals(saved.getUid(), row.get("uid"));
    assertEquals("CODE_PER_THOUSAND", row.get("code"));
    assertEquals("Per thousand", row.get("name"));
    assertEquals(1000, ((Number) row.get("indicatorfactor")).intValue());
    assertEquals(Boolean.TRUE, row.get("indicatornumber"));
    assertEquals(saved.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(saved.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(admin.getId(), ((Number) row.get("lastupdatedby")).longValue());
    assertTrue(((String) row.get("translations")).contains("\"Pour mille\""));

    IndicatorType reloaded = reload(saved);
    assertEquals(saved.getUid(), reloaded.getUid());
    assertEquals("CODE_PER_THOUSAND", reloaded.getCode());
    assertEquals("Per thousand", reloaded.getName());
    assertEquals(1000, reloaded.getFactor());
    assertTrue(reloaded.isNumber());
    assertEquals(saved.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(saved.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(admin.getUid(), reloaded.getLastUpdatedBy().getUid());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Pour mille")),
        reloaded.getTranslations());
  }

  @Test
  @DisplayName("a type without translations is written with an empty translations array")
  void testNullTranslationsAreWrittenAsEmptyArray() {
    IndicatorType type = new IndicatorType("Number", 1, false);
    type.setTranslations(null);
    IndicatorType saved = save(type);

    assertEquals(
        "[]",
        jdbcTemplate.queryForObject(
            "select translations::text from indicatortype where indicatortypeid = ?",
            String.class,
            saved.getId()));
    assertTrue(reload(saved).getTranslations().isEmpty());
  }

  @Test
  @DisplayName("translations is an embedded jsonb set of type jblTranslations")
  void testTranslationsType() {
    ComponentType component =
        assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    CustomType type = assertInstanceOf(CustomType.class, component.getSubtypes()[0]);

    assertInstanceOf(JsonSetBinaryType.class, type.getUserType());
  }

  @Test
  @DisplayName("lastUpdatedBy is a lazy many-to-one")
  void testLastUpdatedByIsLazy() {
    ManyToOneType type =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("lastUpdatedBy"));

    assertFalse(type.isEager(null));
  }

  @Test
  @DisplayName("uid, name, factor, created and lastUpdated are mapped not-null")
  void testNullability() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] nullability = persister.getPropertyNullability();

    assertFalse(nullability[metamodel.getPropertyIndex("uid")]);
    assertFalse(nullability[metamodel.getPropertyIndex("name")]);
    assertFalse(nullability[metamodel.getPropertyIndex("factor")]);
    assertFalse(nullability[metamodel.getPropertyIndex("created")]);
    assertFalse(nullability[metamodel.getPropertyIndex("lastUpdated")]);
    assertTrue(nullability[metamodel.getPropertyIndex("code")]);
    assertTrue(nullability[metamodel.getPropertyIndex("number")]);
    assertTrue(nullability[metamodel.getPropertyIndex("lastUpdatedBy")]);
  }

  @Test
  @DisplayName("created is not updatable")
  void testCreatedIsNotUpdatable() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] updateability = persister.getPropertyUpdateability();

    assertFalse(updateability[metamodel.getPropertyIndex("created")]);
    assertTrue(updateability[metamodel.getPropertyIndex("lastUpdated")]);
  }

  @Test
  @DisplayName("the entity is second-level cached with nonstrict-read-write")
  void testCacheStrategy() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(
        AccessType.NONSTRICT_READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("only the mapped properties are persisted")
  void testMappedProperties() {
    assertEquals(
        List.of(
            "code",
            "created",
            "factor",
            "lastUpdated",
            "lastUpdatedBy",
            "name",
            "number",
            "translations",
            "uid"),
        List.of(persister().getPropertyNames()).stream().sorted().toList());
  }

  @Test
  @DisplayName("updating a loaded type is persisted")
  void testUpdate() {
    IndicatorType saved = save(new IndicatorType("Percent", 100, false));

    IndicatorType loaded = reload(saved);
    loaded.setName("Percentage");
    loaded.setCode("CODE_PERCENT");
    loaded.setFactor(1000);
    loaded.setNumber(true);
    loaded.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Pourcentage")));
    store.update(loaded);
    entityManager.flush();

    IndicatorType reloaded = reload(saved);
    assertEquals("Percentage", reloaded.getName());
    assertEquals("CODE_PERCENT", reloaded.getCode());
    assertEquals(1000, reloaded.getFactor());
    assertTrue(reloaded.isNumber());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Pourcentage")),
        reloaded.getTranslations());
  }

  @Test
  @DisplayName("deleting a type removes only its row")
  void testDelete() {
    IndicatorType deleted = save(new IndicatorType("Deleted", 1, false));
    IndicatorType kept = save(new IndicatorType("Kept", 1, false));

    store.delete(store.get(deleted.getId()));
    entityManager.flush();
    clearSession();

    assertNull(store.get(deleted.getId()));
    assertEquals(kept.getUid(), store.get(kept.getId()).getUid());
  }

  @Test
  @DisplayName("an indicator loads its type and is found by it")
  void testIndicatorReferencesType() {
    IndicatorType type = save(new IndicatorType("Per hundred thousand", 100000, false));
    IndicatorType otherType = save(new IndicatorType("Other", 1, false));
    Indicator indicator = createIndicator('A', type);
    indicatorStore.save(indicator);
    indicatorStore.save(createIndicator('B', otherType));
    entityManager.flush();
    clearSession();
    entityManagerFactory.getCache().evictAll();

    Indicator reloaded = indicatorStore.get(indicator.getId());
    assertEquals(type.getUid(), reloaded.getIndicatorType().getUid());
    assertEquals(100000, reloaded.getIndicatorType().getFactor());
    assertEquals(
        List.of(indicator.getUid()),
        indicatorStore.getAssociatedIndicators(List.of(store.get(type.getId()))).stream()
            .map(Indicator::getUid)
            .toList());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(IndicatorType.class);
  }

  private IndicatorType save(IndicatorType type) {
    store.save(type);
    entityManager.flush();
    return type;
  }

  /** Reloads the type from the database, bypassing the session and the second-level cache. */
  private IndicatorType reload(IndicatorType type) {
    clearSession();
    entityManagerFactory.getCache().evict(IndicatorType.class);
    return store.get(type.getId());
  }
}
