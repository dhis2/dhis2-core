package org.hisp.dhis.metadata;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNotNull;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import jakarta.persistence.EntityManagerFactory;
import java.util.Date;
import java.util.Map;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.type.CustomType;
import org.hibernate.type.ManyToOneType;
import org.hibernate.type.TimestampType;
import org.hisp.dhis.hibernate.jsonb.type.JsonNodeBinaryType;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.hisp.dhis.user.User;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

@Transactional
class MetadataProposalStoreTest extends PostgresIntegrationTestBase {
  private static final ObjectMapper MAPPER = new ObjectMapper();

  private static final Date CREATED = new Date(1_700_000_000_000L);

  private static final Date FINALISED = new Date(1_700_000_360_000L);

  @Autowired private MetadataProposalStore store;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every property is written to its column, enums by name")
  void shouldWriteEveryColumn() {
    User finaliser = makeUser("F");
    userService.addUser(finaliser);
    MetadataProposal proposal = saveFullProposal(finaliser);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, type, status, target, targetuid, createdby, created, change::text as"
                + " change, comment, reason, finalised, finalisedby from metadataproposal"
                + " where proposalid = ?",
            proposal.getId());
    assertEquals("ProposalUi1", row.get("uid"));
    assertEquals("UPDATE", row.get("type"));
    assertEquals("NEEDS_UPDATE", row.get("status"));
    assertEquals("ORGANISATION_UNIT", row.get("target"));
    assertEquals("TargetUid01", row.get("targetuid"));
    assertEquals(getAdminUser().getId(), row.get("createdby"));
    assertEquals(CREATED.getTime(), ((Date) row.get("created")).getTime());
    assertEquals(change(), json((String) row.get("change")));
    assertEquals("A comment", row.get("comment"));
    assertEquals("A reason", row.get("reason"));
    assertEquals(FINALISED.getTime(), ((Date) row.get("finalised")).getTime());
    assertEquals(finaliser.getId(), row.get("finalisedby"));
  }

  @Test
  @DisplayName("every property is read back from its column")
  void shouldReadBackEveryProperty() {
    User finaliser = makeUser("F");
    userService.addUser(finaliser);
    MetadataProposal proposal = saveFullProposal(finaliser);

    MetadataProposal reloaded = reload(proposal);

    assertEquals("ProposalUi1", reloaded.getUid());
    assertEquals(MetadataProposalType.UPDATE, reloaded.getType());
    assertEquals(MetadataProposalStatus.NEEDS_UPDATE, reloaded.getStatus());
    assertEquals(MetadataProposalTarget.ORGANISATION_UNIT, reloaded.getTarget());
    assertEquals("TargetUid01", reloaded.getTargetId());
    assertEquals(getAdminUser().getUid(), reloaded.getCreatedBy().getUid());
    assertEquals(CREATED.getTime(), reloaded.getCreated().getTime());
    assertEquals(change(), reloaded.getChange());
    assertEquals("A comment", reloaded.getComment());
    assertEquals("A reason", reloaded.getReason());
    assertEquals(FINALISED.getTime(), reloaded.getFinalised().getTime());
    assertEquals(finaliser.getUid(), reloaded.getFinalisedBy().getUid());
  }

  @Test
  @DisplayName("saving a minimal proposal fills uid, created and status and leaves the rest null")
  void shouldSaveMinimalProposalWithAutoFields() {
    MetadataProposal proposal =
        MetadataProposal.builder()
            .type(MetadataProposalType.REMOVE)
            .target(MetadataProposalTarget.ORGANISATION_UNIT)
            .targetId("TargetUid01")
            .createdBy(getAdminUser())
            .build();
    store.save(proposal);
    entityManager.flush();

    MetadataProposal reloaded = reload(proposal);

    assertEquals(11, reloaded.getUid().length());
    assertNotNull(reloaded.getCreated());
    assertEquals(MetadataProposalStatus.PROPOSED, reloaded.getStatus());
    assertTrue(reloaded.getChange().isNull());
    assertNull(reloaded.getComment());
    assertNull(reloaded.getReason());
    assertNull(reloaded.getFinalised());
    assertNull(reloaded.getFinalisedBy());
  }

  @Test
  @DisplayName("an update writes the adjusted target id and change and the finalising fields")
  void shouldUpdateAdjustedAndFinalisingFields() {
    MetadataProposal proposal = reload(saveFullProposal(null));
    JsonNode newChange = json("[{\"op\":\"replace\",\"path\":\"/name\",\"value\":\"New\"}]");
    proposal.setTargetId("TargetUid02");
    proposal.setChange(newChange);
    proposal.setStatus(MetadataProposalStatus.REJECTED);
    proposal.setReason("Rejected");
    proposal.setFinalised(FINALISED);
    proposal.setFinalisedBy(getAdminUser());

    store.update(proposal);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select targetuid, change::text as change, status, reason, finalised, finalisedby"
                + " from metadataproposal where proposalid = ?",
            proposal.getId());
    assertEquals("TargetUid02", row.get("targetuid"));
    assertEquals(newChange, json((String) row.get("change")));
    assertEquals("REJECTED", row.get("status"));
    assertEquals("Rejected", row.get("reason"));
    assertEquals(FINALISED.getTime(), ((Date) row.get("finalised")).getTime());
    assertEquals(getAdminUser().getId(), row.get("finalisedby"));
  }

  @Test
  @DisplayName("every column is insertable and updatable")
  void shouldMapEveryPropertyAsInsertableAndUpdatable() {
    EntityPersister persister = persister();
    String[] names = persister.getPropertyNames();
    for (int i = 0; i < names.length; i++) {
      assertTrue(persister.getPropertyInsertability()[i], names[i] + " is not insertable");
      assertTrue(persister.getPropertyUpdateability()[i], names[i] + " is not updatable");
    }
  }

  @Test
  @DisplayName("getByUid finds the proposal by its uid")
  void shouldFindProposalByUid() {
    MetadataProposal proposal = saveFullProposal(null);
    clearSession();

    MetadataProposal found = store.getByUid("ProposalUi1");

    assertEquals(proposal.getId(), found.getId());
    assertNull(store.getByUid("NoProposal1"));
  }

  @Test
  @DisplayName("the not-null columns are not nullable and the optional ones are")
  void shouldMapNullability() {
    for (String property :
        new String[] {"uid", "type", "status", "target", "createdBy", "created", "change"}) {
      assertFalse(isNullable(property), property + " is nullable");
    }
    for (String property :
        new String[] {"targetId", "comment", "reason", "finalised", "finalisedBy"}) {
      assertTrue(isNullable(property), property + " is not nullable");
    }
  }

  @Test
  @DisplayName("createdBy and finalisedBy are lazy user references")
  void shouldMapUserReferencesAsLazy() {
    for (String property : new String[] {"createdBy", "finalisedBy"}) {
      ManyToOneType type =
          assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));

      assertEquals(User.class.getName(), type.getAssociatedEntityName());
      assertFalse(type.isEager(null), property + " is eager");
    }
  }

  @Test
  @DisplayName("change is bound to the jbJsonNode typedef and the dates to timestamps")
  void shouldBindChangeToJsonNodeTypeAndDatesToTimestamps() {
    CustomType change = assertInstanceOf(CustomType.class, persister().getPropertyType("change"));
    assertInstanceOf(JsonNodeBinaryType.class, change.getUserType());

    assertInstanceOf(TimestampType.class, persister().getPropertyType("created"));
    assertInstanceOf(TimestampType.class, persister().getPropertyType("finalised"));
  }

  @Test
  @DisplayName("the entity is not second-level cached")
  void shouldNotBeCached() {
    assertFalse(persister().canReadFromCache());
  }

  private MetadataProposal saveFullProposal(User finaliser) {
    MetadataProposal proposal =
        MetadataProposal.builder()
            .uid("ProposalUi1")
            .type(MetadataProposalType.UPDATE)
            .status(MetadataProposalStatus.NEEDS_UPDATE)
            .target(MetadataProposalTarget.ORGANISATION_UNIT)
            .targetId("TargetUid01")
            .createdBy(getAdminUser())
            .created(CREATED)
            .change(change())
            .comment("A comment")
            .reason("A reason")
            .finalised(FINALISED)
            .finalisedBy(finaliser)
            .build();
    store.save(proposal);
    entityManager.flush();
    return proposal;
  }

  private MetadataProposal reload(MetadataProposal proposal) {
    clearSession();
    return entityManager.find(MetadataProposal.class, proposal.getId());
  }

  private static JsonNode change() {
    return json("[{\"op\":\"replace\",\"path\":\"/shortName\",\"value\":\"OU2\"}]");
  }

  private static JsonNode json(String json) {
    try {
      return MAPPER.readTree(json);
    } catch (Exception ex) {
      throw new IllegalArgumentException(ex);
    }
  }

  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(MetadataProposal.class);
  }
}
