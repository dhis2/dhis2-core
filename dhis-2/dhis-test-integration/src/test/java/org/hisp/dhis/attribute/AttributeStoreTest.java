@Transactional
class AttributeStoreTest extends PostgresIntegrationTestBase {
  @Autowired private AttributeStore store;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  void testGetSupportedClasses() {
    Attribute attribute = new Attribute("AttributeName", ValueType.TEXT);
    attribute.setDataElementAttribute(true);
    assertEquals(1, attribute.getSupportedClasses().size());
    assertTrue(attribute.getSupportedClasses().contains(DataElement.class));
    attribute.setDataElementAttribute(false);
    attribute.setIndicatorAttribute(true);
    attribute.setIndicatorGroupAttribute(true);
    assertEquals(2, attribute.getSupportedClasses().size());
    assertTrue(attribute.getSupportedClasses().contains(Indicator.class));
    assertTrue(attribute.getSupportedClasses().contains(IndicatorGroup.class));
  }

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every property declared by Attribute is written to its column and read back")
  void shouldWriteAndReadBackEveryAttributeColumn() {
    User admin = getAdminUser();
    OptionSet optionSet = createOptionSet('A');
    optionSet.setValueType(ValueType.INTEGER);
    manager.save(optionSet);
    Attribute attribute = createAttribute("Attribute A", ValueType.INTEGER);
    attribute.setCode("ATTR_A");
    attribute.setShortName("Attr A");
    attribute.setDescription("Description A");
    attribute.setMandatory(true);
    attribute.setUnique(true);
    attribute.setSortOrder(3);
    attribute.setOptionSet(optionSet);
    attribute.setDataSetAttribute(true);
    attribute.setUserAttribute(true);
    attribute.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Attribut A")));
    attribute.getSharing().setPublicAccess("rw------");
    attribute.getSharing().setOwner(admin.getUid());
    store.save(attribute, false);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, shortname, description, valuetype, mandatory, isunique,"
                + " sortorder, optionsetid,"
                + " translations::text as translations, sharing->>'public' as publicaccess"
                + " from attribute where attributeid = ?",
            attribute.getId());
    assertEquals("ATTR_A", row.get("code"));
    assertEquals("Attribute A", row.get("name"));
    assertEquals("Attr A", row.get("shortname"));
    assertEquals("Description A", row.get("description"));
    assertEquals("INTEGER", row.get("valuetype"));
    assertEquals(Boolean.TRUE, row.get("mandatory"));
    assertEquals(Boolean.TRUE, row.get("isunique"));
    assertEquals(3, row.get("sortorder"));
    assertEquals(optionSet.getId(), ((Number) row.get("optionsetid")).longValue());
    assertEquals(
        Set.of("DATA_SET", "USER"),
        Set.copyOf(
            jdbcTemplate.queryForList(
                "select jsonb_array_elements_text(objecttypes) from attribute"
                    + " where attributeid = ?",
                String.class,
                attribute.getId())));
    assertTrue(((String) row.get("translations")).contains("\"Attribut A\""));
    assertEquals("rw------", row.get("publicaccess"));

    Attribute reloaded = reload(attribute);
    assertEquals("ATTR_A", reloaded.getCode());
    assertEquals("Attribute A", reloaded.getName());
    assertEquals("Attr A", reloaded.getShortName());
    assertEquals("Description A", reloaded.getDescription());
    assertEquals(ValueType.INTEGER, reloaded.getValueType());
    assertTrue(reloaded.isMandatory());
    assertTrue(reloaded.isUnique());
    assertEquals(3, reloaded.getSortOrder());
    assertEquals(optionSet.getUid(), reloaded.getOptionSet().getUid());
    assertEquals(Set.of("DATA_SET", "USER"), reloaded.getObjectTypes());
    assertTrue(reloaded.isDataSetAttribute());
    assertTrue(reloaded.isUserAttribute());
    assertFalse(reloaded.isDataElementAttribute());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Attribut A")),
        reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(admin.getUid(), reloaded.getSharing().getOwner());
  }

  @Test
  @DisplayName("object types are read from the jsonb column into the object type flags")
  void shouldReadObjectTypesColumnIntoFlags() {
    Attribute saved = save(createAttribute('B'));
    jdbcTemplate.update(
        "update attribute set objecttypes = '[\"OPTION_SET\", \"MAP\"]'::jsonb"
            + " where attributeid = ?",
        saved.getId());

    Attribute reloaded = reload(saved);

    assertTrue(reloaded.isOptionSetAttribute());
    assertTrue(reloaded.isMapAttribute());
    assertFalse(reloaded.isDataElementAttribute());
    assertEquals(
        Set.of(OptionSet.class, org.hisp.dhis.mapping.Map.class),
        Set.copyOf(reloaded.getSupportedClasses()));
  }

  @Test
  @DisplayName("changing an object type flag of a loaded attribute is written on flush")
  void shouldWriteChangedObjectTypeFlagOnFlush() {
    Attribute saved = createAttribute('C');
    saved.setDataElementAttribute(true);
    save(saved);
    Attribute loaded = reload(saved);

    loaded.setDataElementAttribute(false);
    loaded.setIndicatorAttribute(true);
    entityManager.flush();

    assertEquals(
        "[\"INDICATOR\"]",
        jdbcTemplate.queryForObject(
            "select objecttypes::text from attribute where attributeid = ?",
            String.class,
            saved.getId()));
  }

  @Test
  @DisplayName("objectTypes is bound to the jbSet typedef, sharing to jsbObjectSharing")
  void shouldBindJsonbPropertiesToTheirTypedefs() {
    assertEquals(
        HashSet.class,
        assertInstanceOf(JsonBinaryType.class, customType("objectTypes").getUserType())
            .returnedClass());
    assertInstanceOf(SharingJsonBinaryType.class, customType("sharing").getUserType());
  }

  @Test
  @DisplayName("description is bound as text")
  void shouldBindDescriptionAsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
  }

  @Test
  @DisplayName("name, valueType, mandatory and objectTypes are mapped not-null")
  void shouldMapRequiredPropertiesNotNull() {
    assertNotNullable("name");
    assertNotNullable("valueType");
    assertNotNullable("mandatory");
    assertNotNullable("objectTypes");
    assertNullable("code");
    assertNullable("shortName");
    assertNullable("description");
    assertNullable("unique");
    assertNullable("sortOrder");
    assertNullable("optionSet");
    assertNullable("translations");
    assertNullable("sharing");
  }

  @Test
  @DisplayName("the option set is a lazy many-to-one")
  void shouldMapOptionSetLazy() {
    ManyToOneType optionSet =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("optionSet"));

    assertFalse(optionSet.isEager(null));
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("HQL on the entity name Attribute resolves uid and unique")
  void shouldResolveAttributeUidAndUniqueInHql() {
    Attribute unique = createAttribute('D');
    unique.setUnique(true);
    save(unique);
    save(createAttribute('E'));

    List<String> uids =
        entityManager
            .createQuery("select a.uid from Attribute a where a.unique = true", String.class)
            .getResultList();

    assertEquals(List.of(unique.getUid()), uids);
  }

  @Test
  @DisplayName("an uninitialized proxy equals an instance with the same identity and values")
  void shouldEqualProxyWithSameIdentityAndValues() {
    Attribute saved = createAttribute('F');
    saved.setDataElementAttribute(true);
    save(saved);
    clearSession();
    entityManagerFactory.getCache().evict(Attribute.class);
    Attribute copy = createAttribute('F');
    copy.setUid(saved.getUid());
    copy.setDataElementAttribute(true);

    Attribute proxy = entityManager.getReference(Attribute.class, saved.getId());

    assertInstanceOf(HibernateProxy.class, proxy);
    assertEquals(copy, proxy);
    assertEquals(proxy, copy);
    assertEquals(copy.hashCode(), proxy.hashCode());
  }

  @Test
  @DisplayName("a null sharing column is read as empty sharing")
  void shouldReadNullSharingAsEmpty() {
    Attribute saved = save(createAttribute('G'));
    jdbcTemplate.update("update attribute set sharing = null where attributeid = ?", saved.getId());

    Attribute reloaded = reload(saved);

    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Attribute.class);
  }

  private CustomType customType(String property) {
    return assertInstanceOf(CustomType.class, persister().getPropertyType(property));
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private Attribute save(Attribute attribute) {
    store.save(attribute);
    entityManager.flush();
    return attribute;
  }

  /** Reloads the attribute from the database, bypassing the session and the L2 cache. */
  private Attribute reload(Attribute attribute) {
    clearSession();
    entityManagerFactory.getCache().evict(Attribute.class);
    return store.get(attribute.getId());
  }
}
