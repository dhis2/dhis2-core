package org.hisp.dhis.message;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.util.List;
import java.util.Map;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.NoopOptimizer;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.type.ManyToOneType;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.hisp.dhis.user.User;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/**
 * Tests the persistence mapping of {@link UserMessage} to the usermessage table, and its use as the
 * element of {@link MessageConversation#getUserMessages()} (messageconversation_usermessages).
 */
@Transactional
class UserMessageStoreTest extends PostgresIntegrationTestBase {

  @Autowired private MessageConversationStore messageConversationStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  private User userA;

  private User userB;

  @BeforeEach
  void setUp() {
    userA = createAndAddUser("usermessagea");
    userB = createAndAddUser("usermessageb");
  }

  @Test
  @DisplayName(
      "the id is generated by a sequence generator on usermessage_sequence, one nextval per id")
  void testIdGeneratorUsesUserMessageSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "usermessage_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
    assertEquals(1, generator.getDatabaseStructure().getIncrementSize());
    assertInstanceOf(NoopOptimizer.class, generator.getOptimizer());
  }

  @Test
  @DisplayName("the key, user, read and followUp are written to their columns and read back")
  void testColumnsRoundTrip() {
    UserMessage userMessage = userMessage(userA, true, true);
    userMessage.setKey("usermessage-round-trip-key");
    saveConversation(userMessage);

    assertEquals(
        Map.of(
            "usermessagekey",
            "usermessage-round-trip-key",
            "userid",
            userA.getId(),
            "isread",
            true,
            "isfollowup",
            true),
        jdbcTemplate.queryForMap(
            "select usermessagekey, userid, isread, isfollowup from usermessage"
                + " where usermessageid = ?",
            userMessage.getId()));

    clearSessionAndSecondLevelCache();

    UserMessage reloaded = entityManager.find(UserMessage.class, userMessage.getId());
    assertEquals("usermessage-round-trip-key", reloaded.getKey());
    assertEquals(userA.getUid(), reloaded.getUser().getUid());
    assertTrue(reloaded.isRead());
    assertTrue(reloaded.isFollowUp());
  }

  @Test
  @DisplayName("the user and read are mapped not-null, the key and followUp nullable")
  void testNullability() {
    EntityPersister persister = persister();
    boolean[] nullable = persister.getPropertyNullability();

    assertFalse(nullable[persister.getEntityMetamodel().getPropertyIndex("user")]);
    assertFalse(nullable[persister.getEntityMetamodel().getPropertyIndex("read")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("key")]);
    assertTrue(nullable[persister.getEntityMetamodel().getPropertyIndex("followUp")]);
  }

  @Test
  @DisplayName("the user is loaded lazily")
  void testUserIsLazy() {
    ManyToOneType type = assertInstanceOf(ManyToOneType.class, persister().getPropertyType("user"));

    assertFalse(type.isEager(null));
  }

  @Test
  @DisplayName(
      "conversation queries select by the user, read and followUp properties of user messages")
  void testConversationQueriesUseUserReadAndFollowUp() {
    saveConversation(userMessage(userA, false, true), userMessage(userB, true, false));
    clearSessionAndSecondLevelCache();

    assertEquals(1, messageConversationStore.getUnreadUserMessageConversationCount(userA));
    assertEquals(0, messageConversationStore.getUnreadUserMessageConversationCount(userB));
    assertEquals(1, conversations(userA, true, false));
    assertEquals(0, conversations(userB, true, false));
    assertEquals(1, conversations(userA, false, true));
    assertEquals(0, conversations(userB, false, true));
  }

  @Test
  @DisplayName(
      "deleting a user's messages removes their rows and join rows, through HQL on the UserMessage"
          + " entity name")
  void testDeleteUserMessagesHqlResolvesEntityName() {
    UserMessage messageA = userMessage(userA, false, false);
    UserMessage messageB = userMessage(userB, false, false);
    long conversationId = saveConversation(messageA, messageB);
    clearSessionAndSecondLevelCache();

    assertEquals(1, messageConversationStore.deleteUserMessages(userA));

    assertEquals(List.of(messageB.getId()), joinRows(conversationId));
    assertEquals(0, countUserMessageRows(messageA.getId()));
    assertEquals(1, countUserMessageRows(messageB.getId()));
  }

  @Test
  @DisplayName(
      "a conversation saves its user messages by cascade and deletes one removed from it with its"
          + " join row")
  void testConversationOwnsUserMessages() {
    UserMessage messageA = userMessage(userA, false, false);
    UserMessage messageB = userMessage(userB, true, false);
    long conversationId = saveConversation(messageA, messageB);

    assertEquals(
        List.of(messageA.getId(), messageB.getId()).stream().sorted().toList(),
        joinRows(conversationId));

    clearSessionAndSecondLevelCache();

    MessageConversation loaded = messageConversationStore.get(conversationId);
    assertTrue(loaded.remove(userA));
    messageConversationStore.update(loaded);
    entityManager.flush();
    clearSessionAndSecondLevelCache();

    assertEquals(List.of(messageB.getId()), joinRows(conversationId));
    assertEquals(0, countUserMessageRows(messageA.getId()));
    assertEquals(1, countUserMessageRows(messageB.getId()));
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(UserMessage.class);
  }

  private static UserMessage userMessage(User user, boolean read, boolean followUp) {
    UserMessage userMessage = new UserMessage(user, read);
    userMessage.setFollowUp(followUp);
    return userMessage;
  }

  private long saveConversation(UserMessage... userMessages) {
    MessageConversation conversation =
        new MessageConversation("User message subject", userA, MessageType.PRIVATE);
    for (UserMessage userMessage : userMessages) {
      conversation.addUserMessage(userMessage);
    }
    messageConversationStore.save(conversation);
    entityManager.flush();
    return conversation.getId();
  }

  private int conversations(User user, boolean followUpOnly, boolean unreadOnly) {
    return messageConversationStore
        .getMessageConversations(user, null, followUpOnly, unreadOnly, null, null)
        .size();
  }

  /** User message ids of the conversation's join rows, ascending. */
  private List<Integer> joinRows(long conversationId) {
    return jdbcTemplate.queryForList(
        "select usermessageid from messageconversation_usermessages"
            + " where messageconversationid = ? order by usermessageid",
        Integer.class,
        conversationId);
  }

  private int countUserMessageRows(int userMessageId) {
    return jdbcTemplate.queryForObject(
        "select count(*) from usermessage where usermessageid = ?", Integer.class, userMessageId);
  }
}
