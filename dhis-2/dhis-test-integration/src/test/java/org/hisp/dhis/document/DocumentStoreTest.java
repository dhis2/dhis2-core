@Transactional
class DocumentStoreTest extends PostgresIntegrationTestBase {
  @Autowired private DocumentStore store;

  @Autowired private FileResourceStore fileResourceStore;

  @Autowired private IdentifiableObjectManager manager;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void shouldWriteAndReadBackEveryMappedColumn() {
    User admin = getAdminUser();
    FileResource fileResource = saveFileResource('A');
    Attribute attribute = createAttribute('A');
    attribute.setValueType(ValueType.TEXT);
    attribute.setDocumentAttribute(true);
    manager.save(attribute);
    Document document = createDocument("Document A", fileResource.getUid(), false);
    document.setCode("DOC_A");
    document.setContentType("text/plain");
    document.setAttachment(true);
    document.setFileResource(fileResource);
    document.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Document FR")));
    document.addAttributeValue(attribute.getUid(), "value A");
    document.getSharing().setPublicAccess("rw------");
    document.getSharing().setOwner(admin.getUid());
    store.save(document, false);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, url, external, contenttype, attachment, fileresource,"
                + " translations::text as translations,"
                + " attributevalues->?->>'value' as attributevalue,"
                + " sharing->>'public' as publicaccess, sharing->>'owner' as owner"
                + " from document where documentid = ?",
            attribute.getUid(),
            document.getId());
    assertEquals("DOC_A", row.get("code"));
    assertEquals("Document A", row.get("name"));
    assertEquals(fileResource.getUid(), row.get("url"));
    assertFalse((Boolean) row.get("external"));
    assertEquals("text/plain", row.get("contenttype"));
    assertTrue((Boolean) row.get("attachment"));
    assertEquals(fileResource.getId(), ((Number) row.get("fileresource")).longValue());
    assertTrue(((String) row.get("translations")).contains("\"Document FR\""));
    assertEquals("value A", row.get("attributevalue"));
    assertEquals("rw------", row.get("publicaccess"));
    assertEquals(admin.getUid(), row.get("owner"));

    Document reloaded = reload(document);
    assertEquals("DOC_A", reloaded.getCode());
    assertEquals("Document A", reloaded.getName());
    assertEquals(fileResource.getUid(), reloaded.getUrl());
    assertFalse(reloaded.isExternal());
    assertEquals("text/plain", reloaded.getContentType());
    assertTrue(reloaded.getAttachment());
    assertEquals(fileResource.getUid(), reloaded.getFileResource().getUid());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Document FR")),
        reloaded.getTranslations());
    assertEquals("value A", reloaded.getAttributeValues().get(attribute.getUid()));
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(admin.getUid(), reloaded.getSharing().getOwner());
  }

  @Test
  @DisplayName("an external document is stored with its URL and without a file resource")
  void shouldStoreExternalDocumentWithoutFileResource() {
    Document document = save(createDocument("External", "https://example.org/doc", true));

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select url, external, fileresource, attachment from document where documentid = ?",
            document.getId());
    assertEquals("https://example.org/doc", row.get("url"));
    assertTrue((Boolean) row.get("external"));
    assertNull(row.get("fileresource"));
    assertFalse((Boolean) row.get("attachment"));

    Document reloaded = reload(document);
    assertTrue(reloaded.isExternal());
    assertNull(reloaded.getFileResource());
    assertFalse(reloaded.isAttachmentDefaultFalse());
  }

  @Test
  @DisplayName("url is bound as text")
  void shouldBindUrlAsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("url"));
  }

  @Test
  @DisplayName("translations, attribute values and sharing are bound to their jsonb types")
  void shouldBindJsonbProperties() {
    assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    assertInstanceOf(
        JsonAttributeValuesBinaryType.class,
        assertInstanceOf(CustomType.class, persister().getPropertyType("attributeValues"))
            .getUserType());
    assertInstanceOf(
        SharingJsonBinaryType.class,
        assertInstanceOf(CustomType.class, persister().getPropertyType("sharing")).getUserType());
  }

  @Test
  @DisplayName("file resource is a lazy many-to-one")
  void shouldMapFileResourceLazily() {
    assertFalse(
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("fileResource"))
            .isEager(null));
  }

  @Test
  @DisplayName("name, url and external are mapped not-null, the other own properties nullable")
  void shouldMapNameUrlAndExternalNotNull() {
    assertNotNullable("name");
    assertNotNullable("url");
    assertNotNullable("external");
    assertNullable("code");
    assertNullable("contentType");
    assertNullable("attachment");
    assertNullable("fileResource");
    assertNullable("translations");
    assertNullable("attributeValues");
    assertNullable("sharing");
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("documents are counted by the user who created them")
  void shouldCountDocumentsByCreatingUser() {
    User other = makeUser("O");
    userService.addUser(other);
    Document byAdmin = createDocument("By admin", "https://example.org/a", true);
    byAdmin.setCreatedBy(getAdminUser());
    save(byAdmin);
    Document byOther = createDocument("By other", "https://example.org/b", true);
    save(byOther);
    byOther.setCreatedBy(other);
    entityManager.flush();

    assertEquals(1, store.getCountByUser(other));
  }

  @Test
  @DisplayName("the file resource store finds the documents that reference a file resource")
  void shouldFindDocumentsByFileResource() {
    FileResource fileResource = saveFileResource('B');
    Document document = createDocument("File", fileResource.getUid(), false);
    document.setFileResource(fileResource);
    save(document);
    save(createDocument("Other", "https://example.org/c", true));

    assertEquals(
        List.of(document.getUid()),
        fileResourceStore.findDocumentsByFileResource(fileResource.getUid()));
  }

  @Test
  @DisplayName("null attribute values and sharing columns are read as empty values")
  void shouldReadNullJsonbColumnsAsEmpty() {
    Document saved = save(createDocument("Nulls", "https://example.org/d", true));
    jdbcTemplate.update(
        "update document set attributevalues = null, sharing = null where documentid = ?",
        saved.getId());

    Document reloaded = reload(saved);

    assertTrue(reloaded.getAttributeValues().isEmpty());
    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
  }

  private static Document createDocument(String name, String url, boolean external) {
    Document document = new Document(name, url, external, null);
    document.setAutoFields();
    return document;
  }

  private FileResource saveFileResource(char uniqueChar) {
    FileResource fileResource =
        createFileResource(uniqueChar, ("content " + uniqueChar).getBytes(StandardCharsets.UTF_8));
    fileResourceStore.save(fileResource);
    return fileResource;
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Document.class);
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private Document save(Document document) {
    store.save(document);
    entityManager.flush();
    return document;
  }

  /** Reloads the document from the database, bypassing the session and the L2 cache. */
  private Document reload(Document document) {
    clearSession();
    entityManagerFactory.getCache().evict(Document.class);
    return store.get(document.getId());
  }
}
