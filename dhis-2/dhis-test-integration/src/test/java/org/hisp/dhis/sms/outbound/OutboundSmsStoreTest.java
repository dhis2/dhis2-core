package org.hisp.dhis.sms.outbound;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertSame;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.sql.Timestamp;
import java.util.Date;
import java.util.HashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;
import org.hibernate.FetchMode;
import org.hibernate.Hibernate;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.collection.CollectionPersister;
import org.hibernate.persister.entity.AbstractEntityPersister;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.type.CustomType;
import org.hibernate.type.EnumType;
import org.hibernate.type.StringType;
import org.hibernate.type.TextType;
import org.hibernate.type.TimestampType;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the mapping of {@link OutboundSms} and its recipients collection. */
@Transactional
class OutboundSmsStoreTest extends PostgresIntegrationTestBase {

  private static final String RECIPIENTS_ROLE = OutboundSms.class.getName() + ".recipients";

  @Autowired private OutboundSmsStore outboundSmsStore;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("only uid, recipients, date, message, status and sender are persisted")
  void testMappedProperties() {
    assertEquals(
        Set.of("uid", "recipients", "date", "message", "status", "sender"),
        Set.of(persister().getPropertyNames()));
  }

  @Test
  @DisplayName("uid, date, message, status and sender are written to their columns and read back")
  void testColumnsRoundTrip() {
    Date date = new Date(1_600_000_000_000L);
    OutboundSms sms = sms("outSmsRnd01", OutboundSmsStatus.DELIVERED, date, "+4711111111");
    sms.setSender("roundTripSender");
    sms.setSubject("Not persisted subject");
    outboundSmsStore.saveOutboundSms(sms);
    entityManager.flush();

    assertEquals(
        Map.of(
            "uid",
            "outSmsRnd01",
            "date",
            new Timestamp(date.getTime()),
            "message",
            "Message of outSmsRnd01",
            "status",
            OutboundSmsStatus.DELIVERED.ordinal(),
            "sender",
            "roundTripSender"),
        jdbcTemplate.queryForMap(
            "select uid, date, message, status, sender from outbound_sms where id = ?",
            sms.getId()));

    clearSessionAndSecondLevelCache();

    OutboundSms reloaded = outboundSmsStore.get(sms.getId());
    assertEquals("outSmsRnd01", reloaded.getUid());
    assertEquals(date.getTime(), reloaded.getDate().getTime());
    assertEquals("Message of outSmsRnd01", reloaded.getMessage());
    assertEquals(OutboundSmsStatus.DELIVERED, reloaded.getStatus());
    assertEquals("roundTripSender", reloaded.getSender());
    assertNull(reloaded.getSubject());
  }

  @Test
  @DisplayName("recipients are stored as text rows in outbound_sms_recipients and loaded lazily")
  void testRecipientsRoundTrip() {
    OutboundSms sms =
        sms("outSmsRcp01", OutboundSmsStatus.SENT, new Date(), "+4722222222", "+4733333333");
    outboundSmsStore.saveOutboundSms(sms);
    entityManager.flush();

    assertEquals(Set.of("+4722222222", "+4733333333"), recipientRows(sms.getId()));

    clearSessionAndSecondLevelCache();

    OutboundSms reloaded = outboundSmsStore.get(sms.getId());
    assertFalse(Hibernate.isInitialized(reloaded.getRecipients()));
    assertEquals(Set.of("+4722222222", "+4733333333"), reloaded.getRecipients());
  }

  @Test
  @DisplayName("status is stored as the ordinal of the enum constant")
  void testStatusIsStoredAsOrdinal() {
    CustomType type = assertInstanceOf(CustomType.class, persister().getPropertyType("status"));
    EnumType<?> enumType = assertInstanceOf(EnumType.class, type.getUserType());

    assertTrue(enumType.isOrdinal());
    assertEquals(OutboundSmsStatus.class, enumType.returnedClass());
  }

  @Test
  @DisplayName("uid, date and status are mapped not-null, message, sender and recipients not")
  void testNullability() {
    EntityPersister persister = persister();
    boolean[] nullable = persister.getPropertyNullability();

    assertFalse(nullable[propertyIndex(persister, "uid")]);
    assertFalse(nullable[propertyIndex(persister, "date")]);
    assertFalse(nullable[propertyIndex(persister, "status")]);
    assertTrue(nullable[propertyIndex(persister, "message")]);
    assertTrue(nullable[propertyIndex(persister, "sender")]);
    assertTrue(nullable[propertyIndex(persister, "recipients")]);
  }

  @Test
  @DisplayName("message is bound as a string, date as a timestamp and recipient elements as text")
  void testPropertyTypes() {
    EntityPersister persister = persister();

    assertInstanceOf(StringType.class, persister.getPropertyType("message"));
    assertInstanceOf(StringType.class, persister.getPropertyType("sender"));
    assertInstanceOf(TimestampType.class, persister.getPropertyType("date"));
    assertInstanceOf(TextType.class, recipientsPersister().getElementType());
  }

  @Test
  @DisplayName("the entity has no proxy and recipients are a lazy collection fetched by select")
  void testFetching() {
    EntityPersister persister = persister();

    assertFalse(persister.hasProxy());
    assertTrue(recipientsPersister().isLazy());
    assertSame(
        FetchMode.SELECT,
        ((AbstractEntityPersister) persister).getFetchMode(propertyIndex(persister, "recipients")));
  }

  @Test
  @DisplayName("neither the entity nor its recipients are second-level cached")
  void testNotCached() {
    assertFalse(persister().canReadFromCache());
    assertNull(persister().getCacheAccessStrategy());
    assertFalse(recipientsPersister().hasCache());
  }

  @Test
  @DisplayName("get by status returns the matching messages, newest first")
  void testGetByStatusOrdersByDateDescending() {
    outboundSmsStore.saveOutboundSms(
        sms("outSmsOld01", OutboundSmsStatus.FAILED, new Date(1_500_000_000_000L), "+471"));
    outboundSmsStore.saveOutboundSms(
        sms("outSmsNew01", OutboundSmsStatus.FAILED, new Date(1_700_000_000_000L), "+472"));
    outboundSmsStore.saveOutboundSms(
        sms("outSmsSnt01", OutboundSmsStatus.SENT, new Date(1_600_000_000_000L), "+473"));
    clearSessionAndSecondLevelCache();

    assertEquals(
        List.of("outSmsNew01", "outSmsOld01"),
        outboundSmsStore.get(OutboundSmsStatus.FAILED).stream().map(OutboundSms::getUid).toList());
    assertEquals(
        List.of("outSmsNew01"),
        outboundSmsStore.get(OutboundSmsStatus.FAILED, 0, 1, true).stream()
            .map(OutboundSms::getUid)
            .toList());
  }

  @Test
  @DisplayName("deleting a message deletes its recipient rows")
  void testDeleteRemovesRecipients() {
    OutboundSms sms = sms("outSmsDel01", OutboundSmsStatus.SENT, new Date(), "+4744444444");
    outboundSmsStore.saveOutboundSms(sms);
    entityManager.flush();
    long id = sms.getId();

    outboundSmsStore.delete(sms);
    entityManager.flush();

    assertEquals(Set.of(), recipientRows(id));
    assertEquals(
        0,
        jdbcTemplate.queryForObject(
            "select count(*) from outbound_sms where id = ?", Integer.class, id));
  }

  /** Reloads must hit the database, not the second-level cache. */
  private void clearSessionAndSecondLevelCache() {
    clearSession();
    entityManagerFactory.getCache().evictAll();
  }

  private EntityPersister persister() {
    return sessionFactory().getMetamodel().entityPersister(OutboundSms.class);
  }

  private CollectionPersister recipientsPersister() {
    return sessionFactory().getMetamodel().collectionPersister(RECIPIENTS_ROLE);
  }

  private SessionFactoryImplementor sessionFactory() {
    return entityManagerFactory.unwrap(SessionFactoryImplementor.class);
  }

  private static int propertyIndex(EntityPersister persister, String property) {
    return persister.getEntityMetamodel().getPropertyIndex(property);
  }

  private Set<String> recipientRows(long smsId) {
    return new HashSet<>(
        jdbcTemplate.queryForList(
            "select elt from outbound_sms_recipients where outbound_sms_id = ?",
            String.class,
            smsId));
  }

  private static OutboundSms sms(
      String uid, OutboundSmsStatus status, Date date, String... recipients) {
    OutboundSms sms = new OutboundSms();
    sms.setUid(uid);
    sms.setStatus(status);
    sms.setDate(date);
    sms.setMessage("Message of " + uid);
    sms.setRecipients(new HashSet<>(Set.of(recipients)));
    return sms;
  }
}
