/** Tests the persistence mapping of {@link Constant} to the constant table. */
@Transactional
class ConstantStoreTest extends PostgresIntegrationTestBase {

  private static final String ATTRIBUTE_UID = "AttrUid0001";

  @Autowired
  @Qualifier("org.hisp.dhis.constant.ConstantStore")
  private IdentifiableObjectStore<Constant> store;

  @Autowired private ConstantService constantService;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() {
    User admin = getAdminUser();
    Constant constant = new Constant("Pi", 3.14159);
    constant.setCode("CODE_PI");
    constant.setShortName("Pi short");
    constant.setDescription("Ratio of a circle's circumference to its diameter");
    constant.setLastUpdatedBy(admin);
    constant.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Pi fr")));
    constant.setAttributeValues(AttributeValues.of(Map.of(ATTRIBUTE_UID, "attribute value")));
    constant.getSharing().setPublicAccess("rw------");
    Constant saved = save(constant);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, shortname, description, value, created, lastupdated,"
                + " lastupdatedby, userid, translations::text as translations,"
                + " attributevalues::text as attributevalues, sharing->>'public' as publicaccess"
                + " from constant where constantid = ?",
            saved.getId());
    assertEquals(saved.getUid(), row.get("uid"));
    assertEquals("CODE_PI", row.get("code"));
    assertEquals("Pi", row.get("name"));
    assertEquals("Pi short", row.get("shortname"));
    assertEquals("Ratio of a circle's circumference to its diameter", row.get("description"));
    assertEquals(3.14159, ((Number) row.get("value")).doubleValue());
    assertEquals(saved.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(saved.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(admin.getId(), ((Number) row.get("lastupdatedby")).longValue());
    assertEquals(admin.getId(), ((Number) row.get("userid")).longValue());
    assertTrue(((String) row.get("translations")).contains("\"Pi fr\""));
    assertTrue(((String) row.get("attributevalues")).contains("\"attribute value\""));
    assertEquals("rw------", row.get("publicaccess"));

    Constant reloaded = reload(saved);
    assertEquals(saved.getUid(), reloaded.getUid());
    assertEquals("CODE_PI", reloaded.getCode());
    assertEquals("Pi", reloaded.getName());
    assertEquals("Pi short", reloaded.getShortName());
    assertEquals("Ratio of a circle's circumference to its diameter", reloaded.getDescription());
    assertEquals(3.14159, reloaded.getValue());
    assertEquals(saved.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(saved.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(admin.getUid(), reloaded.getLastUpdatedBy().getUid());
    assertEquals(admin.getUid(), reloaded.getCreatedBy().getUid());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Pi fr")), reloaded.getTranslations());
    assertEquals("attribute value", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
  }

  @Test
  @DisplayName("a constant without translations is written with an empty translations array")
  void testNullTranslationsAreWrittenAsEmptyArray() {
    Constant constant = new Constant("No translations", 1);
    constant.setTranslations(null);
    Constant saved = save(constant);

    assertEquals(
        "[]",
        jdbcTemplate.queryForObject(
            "select translations::text from constant where constantid = ?",
            String.class,
            saved.getId()));
    assertTrue(reload(saved).getTranslations().isEmpty());
  }

  @Test
  @DisplayName("null attributevalues and sharing columns load as empty values")
  void testNullJsonbColumnsLoadAsEmptyValues() {
    Constant saved = save(new Constant("Null jsonb", 2));
    jdbcTemplate.update(
        "update constant set attributevalues = null, sharing = null where constantid = ?",
        saved.getId());

    Constant reloaded = reload(saved);
    assertTrue(reloaded.getAttributeValues().isEmpty());
    assertNull(reloaded.getSharing().getPublicAccess());
    reloaded.addAttributeValue(ATTRIBUTE_UID, "added");
    assertEquals("added", reloaded.getAttributeValues().get(ATTRIBUTE_UID));
  }

  @Test
  @DisplayName("description is bound as text")
  void testDescriptionIsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
  }

  @Test
  @DisplayName("translations, sharing and attributeValues use their jsonb user types")
  void testJsonbTypes() {
    ComponentType component =
        assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    CustomType translations = assertInstanceOf(CustomType.class, component.getSubtypes()[0]);
    CustomType sharing = assertInstanceOf(CustomType.class, persister().getPropertyType("sharing"));
    CustomType attributeValues =
        assertInstanceOf(CustomType.class, persister().getPropertyType("attributeValues"));

    assertInstanceOf(JsonSetBinaryType.class, translations.getUserType());
    assertInstanceOf(SharingJsonBinaryType.class, sharing.getUserType());
    assertInstanceOf(JsonAttributeValuesBinaryType.class, attributeValues.getUserType());
  }

  @Test
  @DisplayName("createdBy and lastUpdatedBy are lazy many-to-ones")
  void testUserReferencesAreLazy() {
    assertFalse(manyToOne("createdBy").isEager(null));
    assertFalse(manyToOne("lastUpdatedBy").isEager(null));
  }

  @Test
  @DisplayName("uid, name, shortName, value, created and lastUpdated are mapped not-null")
  void testNullability() {
    assertNotNullable("uid");
    assertNotNullable("name");
    assertNotNullable("shortName");
    assertNotNullable("value");
    assertNotNullable("created");
    assertNotNullable("lastUpdated");
    assertNullable("code");
    assertNullable("description");
    assertNullable("createdBy");
    assertNullable("lastUpdatedBy");
  }

  @Test
  @DisplayName("created is not updatable")
  void testCreatedIsNotUpdatable() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] updateability = persister.getPropertyUpdateability();

    assertFalse(updateability[metamodel.getPropertyIndex("created")]);
    assertTrue(updateability[metamodel.getPropertyIndex("lastUpdated")]);
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void testCacheStrategy() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("only the mapped properties are persisted")
  void testMappedProperties() {
    assertEquals(
        List.of(
            "attributeValues",
            "code",
            "created",
            "createdBy",
            "description",
            "lastUpdated",
            "lastUpdatedBy",
            "name",
            "sharing",
            "shortName",
            "translations",
            "uid",
            "value"),
        List.of(persister().getPropertyNames()).stream().sorted().toList());
  }

  @Test
  @DisplayName("the constant service maps saved constants by uid and by name")
  void testConstantServiceMaps() {
    Constant constant = save(new Constant("Ten", 10));
    clearSession();
    entityManagerFactory.getCache().evict(Constant.class);

    assertEquals(10, constantService.getConstantMap().get(constant.getUid()).getValue());
    assertEquals(10, constantService.getConstantParameterMap().get("Ten"));
    assertEquals(
        List.of(constant.getUid()),
        constantService.getConstantsBetweenByName("Te", 0, 10).stream()
            .map(Constant::getUid)
            .toList());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Constant.class);
  }

  private ManyToOneType manyToOne(String property) {
    return assertInstanceOf(ManyToOneType.class, persister().getPropertyType(property));
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private Constant save(Constant constant) {
    store.save(constant);
    entityManager.flush();
    return constant;
  }

  /** Reloads the constant from the database, bypassing the session and the second-level cache. */
  private Constant reload(Constant constant) {
    clearSession();
    entityManagerFactory.getCache().evict(Constant.class);
    return store.get(constant.getId());
  }
}
