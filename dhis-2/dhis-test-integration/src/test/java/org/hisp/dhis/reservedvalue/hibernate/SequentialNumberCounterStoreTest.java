package org.hisp.dhis.reservedvalue.hibernate;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertInstanceOf;
import static org.junit.jupiter.api.Assertions.assertNull;
import static org.junit.jupiter.api.Assertions.assertTrue;

import jakarta.persistence.EntityManagerFactory;
import java.util.List;
import org.hibernate.engine.spi.SessionFactoryImplementor;
import org.hibernate.id.enhanced.SequenceStyleGenerator;
import org.hibernate.persister.entity.EntityPersister;
import org.hibernate.tuple.entity.EntityMetamodel;
import org.hisp.dhis.reservedvalue.SequentialNumberCounter;
import org.hisp.dhis.reservedvalue.SequentialNumberCounterStore;
import org.hisp.dhis.test.integration.PostgresIntegrationTestBase;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the persistence mapping of {@link SequentialNumberCounter}. */
@Transactional
class SequentialNumberCounterStoreTest extends PostgresIntegrationTestBase {

  @Autowired private SequentialNumberCounterStore store;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("ownerUid, key and counter are written to their columns and read back from them")
  void testColumnsRoundTrip() {
    SequentialNumberCounter saved = save(new SequentialNumberCounter("OwnerColumn", "KEY-#", 7));

    assertEquals(
        List.of("OwnerColumn", "KEY-#", "7"),
        jdbcTemplate.queryForObject(
            "select owneruid, key, counter from sequentialnumbercounter where id = ?",
            (rs, row) ->
                List.of(rs.getString("owneruid"), rs.getString("key"), rs.getString("counter")),
            saved.getId()));

    clearSession();

    SequentialNumberCounter reloaded =
        entityManager.find(SequentialNumberCounter.class, saved.getId());
    assertEquals("OwnerColumn", reloaded.getOwnerUid());
    assertEquals("KEY-#", reloaded.getKey());
    assertEquals(7, reloaded.getCounter());
  }

  @Test
  @DisplayName("ownerUid and key are mapped not-null and counter is mapped nullable")
  void testNullability() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] nullability = persister.getPropertyNullability();

    assertFalse(nullability[metamodel.getPropertyIndex("ownerUid")]);
    assertFalse(nullability[metamodel.getPropertyIndex("key")]);
    assertTrue(nullability[metamodel.getPropertyIndex("counter")]);
  }

  @Test
  @DisplayName("the entity is neither second-level cached nor versioned")
  void testNotCachedAndNotVersioned() {
    EntityPersister persister = persister();

    assertFalse(persister.canReadFromCache());
    assertFalse(persister.isVersioned());
  }

  @Test
  @DisplayName("getting the next values stores the next free value as the counter")
  void testGetNextValuesAdvancesStoredCounter() {
    assertEquals(List.of(1, 2, 3), store.getNextValues("OwnerAdvance", "ADV-#", 3));
    clearSession();
    assertEquals(4, find("OwnerAdvance", "ADV-#").getCounter());

    assertEquals(List.of(4, 5, 6, 7, 8), store.getNextValues("OwnerAdvance", "ADV-#", 5));
    clearSession();
    assertEquals(9, find("OwnerAdvance", "ADV-#").getCounter());
  }

  @Test
  @DisplayName("getting the next values continues from a counter persisted as an entity")
  void testGetNextValuesContinuesEntityPersistedCounter() {
    save(new SequentialNumberCounter("OwnerPersisted", "PER-#", 10));
    clearSession();

    assertEquals(List.of(10, 11), store.getNextValues("OwnerPersisted", "PER-#", 2));
    clearSession();
    assertEquals(12, find("OwnerPersisted", "PER-#").getCounter());
  }

  @Test
  @DisplayName("counters of different owners and keys do not interfere")
  void testSeparateOwnersAndKeysDoNotInterfere() {
    store.getNextValues("OwnerA", "SEP-#", 5);

    assertEquals(List.of(1, 2), store.getNextValues("OwnerA", "SEP-##", 2));
    assertEquals(List.of(1, 2, 3), store.getNextValues("OwnerB", "SEP-#", 3));
    clearSession();

    assertEquals(6, find("OwnerA", "SEP-#").getCounter());
    assertEquals(3, find("OwnerA", "SEP-##").getCounter());
    assertEquals(4, find("OwnerB", "SEP-#").getCounter());
  }

  @Test
  @DisplayName("deleting the counters of an owner removes only that owner's rows")
  void testDeleteCounterRemovesOnlyOwnerRows() {
    store.getNextValues("OwnerDeleted", "DEL-#", 2);
    store.getNextValues("OwnerDeleted", "DEL-##", 2);
    store.getNextValues("OwnerKept", "DEL-#", 2);

    store.deleteCounter("OwnerDeleted");
    clearSession();

    assertNull(find("OwnerDeleted", "DEL-#"));
    assertNull(find("OwnerDeleted", "DEL-##"));
    assertEquals(3, find("OwnerKept", "DEL-#").getCounter());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(SequentialNumberCounter.class);
  }

  private SequentialNumberCounter save(SequentialNumberCounter counter) {
    entityManager.persist(counter);
    entityManager.flush();
    return counter;
  }

  private SequentialNumberCounter find(String ownerUid, String key) {
    return entityManager
        .createQuery(
            "from SequentialNumberCounter where ownerUid = :ownerUid and key = :key",
            SequentialNumberCounter.class)
        .setParameter("ownerUid", ownerUid)
        .setParameter("key", key)
        .getResultStream()
        .findFirst()
        .orElse(null);
  }
}
