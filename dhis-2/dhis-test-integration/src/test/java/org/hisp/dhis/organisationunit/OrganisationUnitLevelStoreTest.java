import org.hisp.dhis.translation.Translation;
import org.hisp.dhis.user.User;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

/** Tests the persistence mapping of {@link OrganisationUnitLevel} to the orgunitlevel table. */
@Transactional
class OrganisationUnitLevelStoreTest extends PostgresIntegrationTestBase {

  @Autowired private OrganisationUnitLevelStore store;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void testIdGeneratorUsesHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every mapped property is written to its column and read back from it")
  void testColumnsRoundTrip() {
    User admin = getAdminUser();
    OrganisationUnitLevel level = new OrganisationUnitLevel(7, "Facility", 2);
    level.setCode("CODE_FACILITY");
    level.setLastUpdatedBy(admin);
    level.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Établissement")));
    OrganisationUnitLevel saved = save(level);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select uid, code, name, level, offlinelevels, created, lastupdated, lastupdatedby,"
                + " translations::text as translations"
                + " from orgunitlevel where orgunitlevelid = ?",
            saved.getId());
    assertEquals(saved.getUid(), row.get("uid"));
    assertEquals("CODE_FACILITY", row.get("code"));
    assertEquals("Facility", row.get("name"));
    assertEquals(7, ((Number) row.get("level")).intValue());
    assertEquals(2, ((Number) row.get("offlinelevels")).intValue());
    assertEquals(saved.getCreated().getTime(), ((Date) row.get("created")).getTime());
    assertEquals(saved.getLastUpdated().getTime(), ((Date) row.get("lastupdated")).getTime());
    assertEquals(admin.getId(), ((Number) row.get("lastupdatedby")).longValue());
    assertTrue(((String) row.get("translations")).contains("\"Établissement\""));

    OrganisationUnitLevel reloaded = reload(saved);
    assertEquals(saved.getUid(), reloaded.getUid());
    assertEquals("CODE_FACILITY", reloaded.getCode());
    assertEquals("Facility", reloaded.getName());
    assertEquals(7, reloaded.getLevel());
    assertEquals(2, reloaded.getOfflineLevels());
    assertEquals(saved.getCreated().getTime(), reloaded.getCreated().getTime());
    assertEquals(saved.getLastUpdated().getTime(), reloaded.getLastUpdated().getTime());
    assertEquals(admin.getUid(), reloaded.getLastUpdatedBy().getUid());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Établissement")),
        reloaded.getTranslations());
  }

  @Test
  @DisplayName("a level without offline levels, code and translations reads them back empty")
  void testOptionalColumnsRoundTripEmpty() {
    OrganisationUnitLevel level = new OrganisationUnitLevel(8, "Ward");
    level.setTranslations(null);
    OrganisationUnitLevel saved = save(level);

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, offlinelevels, translations::text as translations"
                + " from orgunitlevel where orgunitlevelid = ?",
            saved.getId());
    assertNull(row.get("code"));
    assertNull(row.get("offlinelevels"));
    assertEquals("[]", row.get("translations"));

    OrganisationUnitLevel reloaded = reload(saved);
    assertNull(reloaded.getCode());
    assertNull(reloaded.getOfflineLevels());
    assertTrue(reloaded.getTranslations().isEmpty());
  }

  @Test
  @DisplayName("an update of name, offline levels and translations is written to the columns")
  void testUpdate() {
    OrganisationUnitLevel saved = save(new OrganisationUnitLevel(9, "Village", 1));
    OrganisationUnitLevel level = reload(saved);
    level.setName("Hamlet");
    level.setOfflineLevels(3);
    level.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Hameau")));
    store.update(level);
    entityManager.flush();

    OrganisationUnitLevel reloaded = reload(saved);
    assertEquals("Hamlet", reloaded.getName());
    assertEquals(3, reloaded.getOfflineLevels());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Hameau")), reloaded.getTranslations());
  }

  @Test
  @DisplayName("translations is an embedded jsonb set of type jblTranslations")
  void testTranslationsType() {
    ComponentType component =
        assertInstanceOf(ComponentType.class, persister().getPropertyType("translations"));
    CustomType type = assertInstanceOf(CustomType.class, component.getSubtypes()[0]);

    assertInstanceOf(JsonSetBinaryType.class, type.getUserType());
  }

  @Test
  @DisplayName("lastUpdatedBy is a lazy many-to-one")
  void testLastUpdatedByIsLazy() {
    ManyToOneType type =
        assertInstanceOf(ManyToOneType.class, persister().getPropertyType("lastUpdatedBy"));

    assertFalse(type.isEager(null));
  }

  @Test
  @DisplayName("uid, name, level, created and lastUpdated are mapped not-null")
  void testNullability() {
    assertNotNullable("uid");
    assertNotNullable("name");
    assertNotNullable("level");
    assertNotNullable("created");
    assertNotNullable("lastUpdated");
    assertNullable("code");
    assertNullable("offlineLevels");
    assertNullable("lastUpdatedBy");
    assertNullable("translations");
  }

  @Test
  @DisplayName("created is not updatable")
  void testCreatedIsNotUpdatable() {
    EntityPersister persister = persister();
    EntityMetamodel metamodel = persister.getEntityMetamodel();
    boolean[] updateability = persister.getPropertyUpdateability();

    assertFalse(updateability[metamodel.getPropertyIndex("created")]);
    assertTrue(updateability[metamodel.getPropertyIndex("lastUpdated")]);
  }

  @Test
  @DisplayName("the entity is second-level cached with nonstrict-read-write")
  void testCacheStrategy() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(
        AccessType.NONSTRICT_READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("only the mapped properties are persisted")
  void testMappedProperties() {
    assertEquals(
        List.of(
            "code",
            "created",
            "lastUpdated",
            "lastUpdatedBy",
            "level",
            "name",
            "offlineLevels",
            "translations",
            "uid"),
        List.of(persister().getPropertyNames()).stream().sorted().toList());
  }

  @Test
  @DisplayName("getByLevel finds the level by its number")
  void testGetByLevel() {
    save(new OrganisationUnitLevel(7, "Facility"));
    OrganisationUnitLevel ward = save(new OrganisationUnitLevel(8, "Ward"));
    clearSession();
    entityManagerFactory.getCache().evict(OrganisationUnitLevel.class);

    assertEquals(ward.getUid(), store.getByLevel(8).getUid());
    assertNull(store.getByLevel(9));
  }

  @Test
  @DisplayName("getAllEqName finds the levels with the given name")
  void testGetAllEqName() {
    OrganisationUnitLevel facility = save(new OrganisationUnitLevel(7, "Facility"));
    save(new OrganisationUnitLevel(8, "Ward"));
    clearSession();

    assertEquals(
        List.of(facility.getUid()),
        store.getAllEqName("Facility").stream().map(OrganisationUnitLevel::getUid).toList());
  }

  @Test
  @DisplayName("deleteAll removes every level through its HQL delete")
  void testDeleteAll() {
    save(new OrganisationUnitLevel(7, "Facility"));
    save(new OrganisationUnitLevel(8, "Ward"));

    store.deleteAll();
    clearSession();
    entityManagerFactory.getCache().evict(OrganisationUnitLevel.class);

    assertEquals(0, jdbcTemplate.queryForObject("select count(*) from orgunitlevel", Long.class));
    assertTrue(store.getAll().isEmpty());
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(OrganisationUnitLevel.class);
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private OrganisationUnitLevel save(OrganisationUnitLevel level) {
    store.save(level);
    entityManager.flush();
    return level;
  }

  /** Reloads the level from the database, bypassing the session and the second-level cache. */
  private OrganisationUnitLevel reload(OrganisationUnitLevel level) {
    clearSession();
    entityManagerFactory.getCache().evict(OrganisationUnitLevel.class);
    return store.get(level.getId());
  }
}
