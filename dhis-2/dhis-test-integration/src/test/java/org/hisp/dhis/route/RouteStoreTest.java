import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.transaction.annotation.Transactional;

@Transactional
class RouteStoreTest extends PostgresIntegrationTestBase {
  @Autowired private RouteStore store;

  @Autowired private JdbcTemplate jdbcTemplate;

  @Autowired private EntityManagerFactory entityManagerFactory;

  @Test
  @DisplayName("the id is generated by a sequence generator on hibernate_sequence")
  void shouldGenerateIdFromHibernateSequence() {
    SequenceStyleGenerator generator =
        assertInstanceOf(SequenceStyleGenerator.class, persister().getIdentifierGenerator());

    assertEquals(
        "hibernate_sequence",
        generator.getDatabaseStructure().getPhysicalName().getObjectName().getText());
  }

  @Test
  @DisplayName("every property declared by Route is written to its column and read back from it")
  void shouldWriteAndReadBackEveryRouteColumn() {
    User admin = getAdminUser();
    Route route = createRoute("Route A", "https://stub/api/**");
    route.setCode("ROUTE_A");
    route
        .setDescription("Description A")
        .setDisabled(true)
        .setHeaders(new HashMap<>(Map.of("X-Header", "value")))
        .setAuth(new ApiTokenAuthScheme().setToken("token-a"))
        .setAuthorities(new ArrayList<>(List.of("F_ROUTE_A", "F_ROUTE_B")))
        .setResponseTimeoutSeconds(30);
    route.setTranslations(Set.of(new Translation(new Locale("fr"), "NAME", "Route fr")));
    route.getSharing().setPublicAccess("rw------");
    route.getSharing().setOwner(admin.getUid());
    route.addAttributeValue("AttrUid0001", "attribute value");
    store.save(route, false);
    entityManager.flush();

    Map<String, Object> row =
        jdbcTemplate.queryForMap(
            "select code, name, description, disabled, url, headers->>'X-Header' as header,"
                + " auth->>'type' as authtype, auth->>'token' as token,"
                + " authorities::text as authorities, responsetimeoutseconds,"
                + " translations::text as translations, sharing->>'public' as publicaccess,"
                + " attributevalues->'AttrUid0001'->>'value' as attributevalue"
                + " from route where routeid = ?",
            route.getId());
    assertEquals("ROUTE_A", row.get("code"));
    assertEquals("Route A", row.get("name"));
    assertEquals("Description A", row.get("description"));
    assertEquals(Boolean.TRUE, row.get("disabled"));
    assertEquals("https://stub/api/**", row.get("url"));
    assertEquals("value", row.get("header"));
    assertEquals("api-token", row.get("authtype"));
    assertEquals("token-a", row.get("token"));
    assertEquals("[\"F_ROUTE_A\", \"F_ROUTE_B\"]", row.get("authorities"));
    assertEquals(30, row.get("responsetimeoutseconds"));
    assertTrue(((String) row.get("translations")).contains("\"Route fr\""));
    assertEquals("rw------", row.get("publicaccess"));
    assertEquals("attribute value", row.get("attributevalue"));

    Route reloaded = reload(route);
    assertEquals("ROUTE_A", reloaded.getCode());
    assertEquals("Route A", reloaded.getName());
    assertEquals("Description A", reloaded.getDescription());
    assertTrue(reloaded.isDisabled());
    assertEquals("https://stub/api/**", reloaded.getUrl());
    assertEquals(Map.of("X-Header", "value"), reloaded.getHeaders());
    assertEquals(
        "token-a", assertInstanceOf(ApiTokenAuthScheme.class, reloaded.getAuth()).getToken());
    assertEquals(List.of("F_ROUTE_A", "F_ROUTE_B"), reloaded.getAuthorities());
    assertEquals(30, reloaded.getResponseTimeoutSeconds());
    assertEquals(
        Set.of(new Translation(new Locale("fr"), "NAME", "Route fr")), reloaded.getTranslations());
    assertEquals("rw------", reloaded.getSharing().getPublicAccess());
    assertEquals(admin.getUid(), reloaded.getSharing().getOwner());
    assertEquals("attribute value", reloaded.getAttributeValues().get("AttrUid0001"));
  }

  @Test
  @DisplayName("the jsonb properties are bound to their typedefs")
  void shouldBindJsonbPropertiesToTheirTypedefs() {
    assertEquals(HashMap.class, jsonBinaryType("headers").returnedClass());
    assertEquals(ArrayList.class, jsonBinaryType("authorities").returnedClass());
    assertEquals(AuthScheme.class, jsonBinaryType("auth").returnedClass());
    assertInstanceOf(SharingJsonBinaryType.class, customType("sharing").getUserType());
    assertInstanceOf(
        JsonAttributeValuesBinaryType.class, customType("attributeValues").getUserType());
  }

  @Test
  @DisplayName("description and url are bound as text")
  void shouldBindDescriptionAndUrlAsText() {
    assertInstanceOf(TextType.class, persister().getPropertyType("description"));
    assertInstanceOf(TextType.class, persister().getPropertyType("url"));
  }

  @Test
  @DisplayName("name, headers and authorities are mapped not-null, the other properties nullable")
  void shouldMapNameHeadersAndAuthoritiesNotNull() {
    assertNotNullable("name");
    assertNotNullable("headers");
    assertNotNullable("authorities");
    assertNullable("code");
    assertNullable("description");
    assertNullable("url");
    assertNullable("auth");
    assertNullable("translations");
    assertNullable("sharing");
    assertNullable("attributeValues");
  }

  @Test
  @DisplayName("the entity is second-level cached with read-write")
  void shouldCacheEntityReadWrite() {
    EntityPersister persister = persister();

    assertTrue(persister.canReadFromCache());
    assertEquals(AccessType.READ_WRITE, persister.getCacheAccessStrategy().getAccessType());
  }

  @Test
  @DisplayName("a route is found by its code")
  void shouldGetRouteByCode() {
    Route route = createRoute("Route B", "https://stub");
    route.setCode("ROUTE_B");
    save(route);
    clearSession();

    assertEquals(route.getUid(), store.getByCodeNoAcl("ROUTE_B").getUid());
  }

  @Test
  @DisplayName("an uninitialized proxy equals an instance with the same uid, code, name and values")
  void shouldEqualProxyWithSameIdentityAndValues() {
    Route saved = save(createRoute("Route C", "https://stub"));
    clearSession();
    entityManagerFactory.getCache().evict(Route.class);
    Route copy = createRoute("Route C", "https://stub");
    copy.setUid(saved.getUid());

    Route proxy = entityManager.getReference(Route.class, saved.getId());

    assertInstanceOf(HibernateProxy.class, proxy);
    assertEquals(copy, proxy);
    assertEquals(proxy, copy);
    assertEquals(copy.hashCode(), proxy.hashCode());
  }

  @Test
  @DisplayName("null translations, sharing and attribute values columns are read as empty")
  void shouldReadNullJsonbColumnsAsEmpty() {
    Route saved = save(createRoute("Route D", "https://stub"));
    jdbcTemplate.update(
        "update route set translations = null, sharing = null, attributevalues = null"
            + " where routeid = ?",
        saved.getId());

    Route reloaded = reload(saved);

    assertTrue(reloaded.getTranslations().isEmpty());
    assertEquals("Route D", reloaded.getDisplayName());
    assertNotNull(reloaded.getSharing());
    assertNull(reloaded.getSharing().getPublicAccess());
    assertTrue(reloaded.getAttributeValues().isEmpty());
  }

  private static Route createRoute(String name, String url) {
    Route route = new Route().setUrl(url);
    route.setAutoFields();
    route.setName(name);
    return route;
  }

  private EntityPersister persister() {
    return entityManagerFactory
        .unwrap(SessionFactoryImplementor.class)
        .getMetamodel()
        .entityPersister(Route.class);
  }

  private CustomType customType(String property) {
    return assertInstanceOf(CustomType.class, persister().getPropertyType(property));
  }

  private JsonBinaryType jsonBinaryType(String property) {
    return assertInstanceOf(JsonBinaryType.class, customType(property).getUserType());
  }

  private void assertNotNullable(String property) {
    assertFalse(isNullable(property), property + " is mapped nullable");
  }

  private void assertNullable(String property) {
    assertTrue(isNullable(property), property + " is mapped not-null");
  }

  /** {@link EntityPersister#getPropertyNullability()} holds a nullable flag per property. */
  private boolean isNullable(String property) {
    EntityPersister persister = persister();
    return persister
        .getPropertyNullability()[persister.getEntityMetamodel().getPropertyIndex(property)];
  }

  private Route save(Route route) {
    store.save(route);
    entityManager.flush();
    return route;
  }

  /** Reloads the route from the database, bypassing the session and the L2 cache. */
  private Route reload(Route route) {
    clearSession();
    entityManagerFactory.getCache().evict(Route.class);
    return store.get(route.getId());
  }
}
